#!/usr/bin/env python3
"""Analyze and compute marginal energy per token (J/token = ΔE/ΔN) on Apple Silicon.

Parses energy measurement log files generated by `scripts/energy_per_token.py`
for 8,192 and 32,768 step horizons across repeats, computes marginal energy:
    ΔE = E(32768) - E(8192)
    ΔN = 32768 - 8192 = 24,576 tokens
    Marginal J/token = ΔE / ΔN
so startup energy and constant framework initialization cancel out.
"""

import argparse
import hashlib
import json
import os
import re
import sys


def eprint(*args, **kwargs):
    print(*args, file=sys.stderr, **kwargs)


def sha256_file(filepath):
    if not os.path.exists(filepath):
        return None
    h = hashlib.sha256()
    with open(filepath, "rb") as f:
        while chunk := f.read(65536):
            h.update(chunk)
    return h.hexdigest()


def parse_energy_file(filepath):
    """Extract metrics from an energy_per_token.py output log."""
    if not os.path.exists(filepath):
        return None

    with open(filepath, "r", encoding="utf-8") as f:
        content = f.read()

    net_j = None
    gross_j = None
    tokens = None
    wall_time = None
    tok_per_sec = None

    m_net = re.search(r"NET energy \(idle removed\)\s*:\s*([0-9.]+)\s*J", content)
    if m_net:
        net_j = float(m_net.group(1))

    m_gross = re.search(r"GROSS energy\s*:\s*([0-9.]+)\s*J", content)
    if m_gross:
        gross_j = float(m_gross.group(1))

    m_tok = re.search(r"tokens\s*:\s*(\d+)", content)
    if m_tok:
        tokens = int(m_tok.group(1))

    m_time = re.search(r"wall time\s*:\s*([0-9.]+)\s*s", content)
    if m_time:
        wall_time = float(m_time.group(1))

    m_rate = re.search(r"decode rate\s*:\s*([0-9.]+)\s*tok/s", content)
    if m_rate:
        tok_per_sec = float(m_rate.group(1))

    idle_mean_mw = None
    idle_std_mw = None
    m_idle = re.search(r"idle power \(not the model\):\s*([0-9.]+)\s*mW", content)
    if m_idle:
        idle_mean_mw = float(m_idle.group(1))

    m_std = re.search(r"idle spread \(std / range\)\s*:\s*±([0-9.]+)\s*mW", content)
    if m_std:
        idle_std_mw = float(m_std.group(1))

    sampler = None
    m_samp = re.search(r"sampler\s*:\s*(\w+)", content)
    if m_samp:
        sampler = m_samp.group(1)

    power_field = None
    m_field = re.search(r"power field used\s*:\s*(.+)", content)
    if m_field:
        power_field = m_field.group(1).strip()

    if net_j is None or tokens is None:
        return None

    return {
        "tokens": tokens,
        "net_j": net_j,
        "gross_j": gross_j,
        "wall_time": wall_time,
        "tok_per_sec": tok_per_sec,
        "idle_mean_mw": idle_mean_mw,
        "idle_std_mw": idle_std_mw,
        "sampler": sampler,
        "power_field": power_field,
    }


def analyze_directory(dirpath, repeats=3, k_low=10240, k_high=32768):
    """Aggregate all runs in the directory and compute marginal metrics."""
    models = {
        "integer_baseline": {
            "name": "Integer Baseline (3b463398, same-input-step)",
            "prefix": "energy-integer-baseline",
        },
        "integer_phase_b": {
            "name": "Integer Phase B Speedup (bc69b869, same-input-step)",
            "prefix": "energy-integer-phase-b",
        },
        "integer": {
            "name": "Integer Bundle (w256, same-input-step)",
            "prefix": "energy-integer",
        },
        "continuous_ff": {
            "name": "Continuous FF Parent (fit256, same-input-step)",
            "prefix": "energy-continuous-ff",
        },
        "llama_smollm2": {
            "name": "SmolLM2-135M Q4_0 (llama.cpp comparator)",
            "prefix": "energy-llama-smollm2",
        },
    }

    results = {}
    for m_key, m_info in models.items():
        prefix = m_info["prefix"]
        runs_low = []
        runs_high = []

        for r in range(1, repeats + 1):
            flow = os.path.join(dirpath, f"{prefix}-k{k_low}-rep{r}.txt")
            fhigh = os.path.join(dirpath, f"{prefix}-k{k_high}-rep{r}.txt")

            dlow = parse_energy_file(flow)
            dhigh = parse_energy_file(fhigh)

            if dlow:
                runs_low.append(dlow)
            if dhigh:
                runs_high.append(dhigh)

        if not runs_low and not runs_high:
            continue

        results[m_key] = {
            "name": m_info["name"],
            "k_low": k_low,
            "k_high": k_high,
            "runs_low": runs_low,
            "runs_high": runs_high,
        }

    return results


def format_summary(results, bundle_dir=None, checkpoint_dir=None, baseline_bin=None, optimized_bin=None):
    """Generate text report and structured JSON dictionary from analysis results."""
    lines = []
    lines.append("=" * 80)
    lines.append("APPLE SILICON M1 MARGINAL SERVING ENERGY REPORT (Track T3)")
    lines.append("=" * 80)
    lines.append("Measurement Paradigm:")
    lines.append("  Same-input stepping through sliding full256 context (zero sampling/stop tokens).")
    lines.append("  Marginal energy ΔE/ΔN cancels startup overhead.")
    lines.append("Working Set & Cache Statement:")
    lines.append("  Integer active parameters: 847,876 B (~848 KB in hard-parameters.bin).")
    lines.append("  Active table lookups: ~128 KB. Total touched working set: ~0.95-1.0 MB/token.")
    lines.append("  (Note: report working set bytes touched per token, NOT 12.8 MB bundle file size).")
    lines.append("=" * 80)

    # Model identity & provenance verification
    provenance = {}
    if bundle_dir:
        b_manifest = os.path.join(bundle_dir, "manifest.json")
        b_bundle = os.path.join(bundle_dir, "bundle.json")
        b_params = os.path.join(bundle_dir, "model", "hard-parameters.bin")
        provenance["bundle"] = {
            "path": bundle_dir,
            "manifest_sha256": sha256_file(b_manifest),
            "bundle_json_sha256": sha256_file(b_bundle),
            "hard_parameters_bin_sha256": sha256_file(b_params),
            "hard_parameters_bytes": os.path.getsize(b_params) if os.path.exists(b_params) else None,
        }
    if checkpoint_dir:
        c_ckpt = os.path.join(checkpoint_dir, "checkpoint.json")
        c_model = os.path.join(checkpoint_dir, "model.safetensors")
        provenance["ff_checkpoint"] = {
            "path": checkpoint_dir,
            "checkpoint_json_sha256": sha256_file(c_ckpt),
            "model_safetensors_sha256": sha256_file(c_model),
            "model_safetensors_bytes": os.path.getsize(c_model) if os.path.exists(c_model) else None,
        }
    if baseline_bin or optimized_bin:
        provenance["binaries"] = {}
        if baseline_bin and os.path.exists(baseline_bin):
            provenance["binaries"]["baseline"] = {
                "path": baseline_bin,
                "commit": "3b463398c199d6d1b268b8b0e8c0fa3e5a52ff61",
                "sha256": sha256_file(baseline_bin),
                "bytes": os.path.getsize(baseline_bin),
            }
        if optimized_bin and os.path.exists(optimized_bin):
            provenance["binaries"]["phase_b_optimized"] = {
                "path": optimized_bin,
                "commit": "bc69b869fa047961d1bcbfafe58b35053ff25dc6",
                "sha256": sha256_file(optimized_bin),
                "bytes": os.path.getsize(optimized_bin),
            }

    model_relation = (
        "Different models: bundle-quaternion-1 was packed from "
        "fit-quaternion-rounding-3/packed-model (step 8348). That model was trained with learned "
        "rounding on fit-quaternion-projected-1 (step 7836), which originated from "
        "fit256-quaternion-3 (step 7324). bundle-quaternion-1 and fit256-quaternion-3 are DIFFERENT models."
    )
    provenance["model_divergence_record"] = model_relation

    lines.append(f"Model Lineage Record: {model_relation}")
    lines.append("=" * 80)

    if not results:
        lines.append("No completed energy measurements found in output directory.")
        lines.append("Run `./scripts/integer-m1-energy.sh` to produce measurements.")
        lines.append("=" * 80)
        return "\n".join(lines), {"provenance": provenance, "models": {}}

    first_k_low = next(iter(results.values()))["k_low"] if results else 4096
    first_k_high = next(iter(results.values()))["k_high"] if results else 16384
    first_delta_n = first_k_high - first_k_low
    lines.append(f"{'Model':<48} | {f'E({first_k_low}) Net J':<15} | {f'E({first_k_high}) Net J':<15} | {f'Marginal J/tok (ΔE/{first_delta_n})':<26}")
    lines.append("-" * 112)

    summary_data = {
        "schema": "uor-r4.m1-marginal-energy-summary/1",
        "provenance": provenance,
        "models": {},
    }

    for m_key, data in results.items():
        k_low = data["k_low"]
        k_high = data["k_high"]
        delta_n = k_high - k_low
        runs_low = data["runs_low"]
        runs_high = data["runs_high"]

        e_low_vals = [r["net_j"] for r in runs_low]
        e_high_vals = [r["net_j"] for r in runs_high]

        e_low_mean = sum(e_low_vals) / len(e_low_vals) if e_low_vals else 0.0
        e_high_mean = sum(e_high_vals) / len(e_high_vals) if e_high_vals else 0.0

        marginal_mean = (e_high_mean - e_low_mean) / float(delta_n) if (e_low_vals and e_high_vals) else 0.0

        n_pairs = min(len(e_low_vals), len(e_high_vals))
        paired_marginals = [(e_high_vals[i] - e_low_vals[i]) / float(delta_n) for i in range(n_pairs)]
        if paired_marginals:
            min_m = min(paired_marginals)
            max_m = max(paired_marginals)
            m_range_str = f"{marginal_mean:.6f} [{min_m:.6f}..{max_m:.6f}]"
        else:
            m_range_str = f"{marginal_mean:.6f}"

        e_low_str = f"{e_low_mean:.4f} (n={len(e_low_vals)})"
        e_high_str = f"{e_high_mean:.4f} (n={len(e_high_vals)})"

        lines.append(f"{data['name']:<48} | {e_low_str:<15} | {e_high_str:<15} | {m_range_str:<26}")

        idle_means = [r["idle_mean_mw"] for r in (runs_low + runs_high) if r.get("idle_mean_mw") is not None]
        idle_stds = [r["idle_std_mw"] for r in (runs_low + runs_high) if r.get("idle_std_mw") is not None]
        samplers = list(set([r["sampler"] for r in (runs_low + runs_high) if r.get("sampler")]))
        power_fields = list(set([r["power_field"] for r in (runs_low + runs_high) if r.get("power_field")]))

        summary_data["models"][m_key] = {
            "name": data["name"],
            "sampler": samplers[0] if len(samplers) == 1 else samplers,
            "power_field": power_fields[0] if len(power_fields) == 1 else power_fields,
            "k_low": k_low,
            "k_high": k_high,
            "delta_n": delta_n,
            "idle_mean_mw": sum(idle_means) / len(idle_means) if idle_means else None,
            "idle_std_mw": sum(idle_stds) / len(idle_stds) if idle_stds else None,
            "e_low_mean_net_j": e_low_mean,
            "e_low_net_j_repeats": e_low_vals,
            "e_high_mean_net_j": e_high_mean,
            "e_high_net_j_repeats": e_high_vals,
            "marginal_j_per_token_mean": marginal_mean,
            "marginal_j_per_token_repeats": paired_marginals,
        }

    lines.append("=" * 112)

    # Report Phase B speedup and energy delta if both baseline and phase B are present
    if "integer_baseline" in summary_data["models"] and "integer_phase_b" in summary_data["models"]:
        base_m = summary_data["models"]["integer_baseline"]["marginal_j_per_token_mean"]
        opt_m = summary_data["models"]["integer_phase_b"]["marginal_j_per_token_mean"]
        m_delta_pct = ((opt_m - base_m) / base_m) * 100.0 if base_m > 0 else 0.0
        lines.append("\nPHASE B SPEEDUP & ENERGY DELTA (bc69b869 vs 3b463398):")
        lines.append(f"  Baseline Marginal Energy : {base_m:.6f} J/tok")
        lines.append(f"  Phase B Marginal Energy  : {opt_m:.6f} J/tok ({m_delta_pct:+.2f}%)")

    # Evaluate pre-registered decision rule
    int_candidate_key = None
    for cand in ["integer_phase_b", "integer", "integer_baseline"]:
        if cand in summary_data["models"]:
            int_candidate_key = cand
            break

    if int_candidate_key and "continuous_ff" in summary_data["models"]:
        int_m = summary_data["models"][int_candidate_key]["marginal_j_per_token_mean"]
        ff_m = summary_data["models"]["continuous_ff"]["marginal_j_per_token_mean"]
        int_name = summary_data["models"][int_candidate_key]["name"]
        lines.append(f"\nPRE-REGISTERED DECISION EVALUATION ({int_name} vs Continuous FF):")
        lines.append(f"  Integer Marginal J/tok      : {int_m:.6f} J/tok")
        lines.append(f"  Continuous FF Marginal J/tok: {ff_m:.6f} J/tok")
        if int_m >= ff_m:
            lines.append("  VERDICT: Integer J/token >= FF J/token.")
            lines.append("    -> Software product emulation costs energy.")
            lines.append("    -> The stack port then uses grouped LUT accumulation (T-MAC style)")
            lines.append("       and fewer bytes touched, not per-product tables.")
        else:
            lines.append("  VERDICT: Integer J/token < FF J/token.")
            lines.append("    -> Integer kernel shift-add/table design achieves energy advantage.")
            lines.append("    -> Current kernels stay.")
    else:
        lines.append("\nPRE-REGISTERED DECISION EVALUATION: Awaiting execution of both integer and continuous FF workloads.")

    if "llama_smollm2" in summary_data["models"]:
        llama_m = summary_data["models"]["llama_smollm2"]["marginal_j_per_token_mean"]
        lines.append(f"\n  SmolLM2-135M Q4_0 Reference: {llama_m:.6f} J/tok (Reference point only, not matched quality)")

    lines.append("\n" + "=" * 112)
    return "\n".join(lines), summary_data


def main():
    parser = argparse.ArgumentParser(description="Analyze marginal energy measurements (ΔE/ΔN).")
    parser.add_argument("dir", help="Path to output directory containing energy-*.txt logs")
    parser.add_argument("--repeats", type=int, default=3, help="Number of repeats (default: 3)")
    parser.add_argument("--k-low", type=int, default=10240, help="Low step horizon (default: 10240)")
    parser.add_argument("--k-high", type=int, default=32768, help="High step horizon (default: 32768)")
    parser.add_argument("--baseline-bin", help="Path to baseline integer binary for provenance")
    parser.add_argument("--optimized-bin", help="Path to optimized integer binary for provenance")
    parser.add_argument("--bundle-dir", help="Path to integer bundle for identity binding")
    parser.add_argument("--checkpoint-dir", help="Path to FF checkpoint for identity binding")
    parser.add_argument("--summary-out", help="Path to write JSON summary (e.g. under docs/evidence/)")
    parser.add_argument("--json", action="store_true", help="Print JSON summary to stdout")
    args = parser.parse_args()

    results = analyze_directory(args.dir, args.repeats, args.k_low, args.k_high)
    report_text, summary_data = format_summary(
        results,
        args.bundle_dir,
        args.checkpoint_dir,
        args.baseline_bin,
        args.optimized_bin,
    )

    print(report_text)

    # Save summary files in raw output directory
    summary_txt_path = os.path.join(args.dir, "summary.txt")
    try:
        with open(summary_txt_path, "w", encoding="utf-8") as f:
            f.write(report_text + "\n")
    except Exception as e:
        eprint(f"Warning: could not write {summary_txt_path}: {e}")

    summary_json_path = os.path.join(args.dir, "summary.json")
    try:
        with open(summary_json_path, "w", encoding="utf-8") as f:
            json.dump(summary_data, f, indent=2)
    except Exception as e:
        eprint(f"Warning: could not write {summary_json_path}: {e}")

    # If requested, write summary JSON to destination (e.g. docs/evidence)
    if args.summary_out:
        os.makedirs(os.path.dirname(os.path.abspath(args.summary_out)), exist_ok=True)
        with open(args.summary_out, "w", encoding="utf-8") as f:
            json.dump(summary_data, f, indent=2)
        print(f"Summary JSON saved to {args.summary_out}")

    if args.json:
        print(json.dumps(summary_data, indent=2))


if __name__ == "__main__":
    main()
