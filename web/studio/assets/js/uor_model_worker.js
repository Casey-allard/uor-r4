// Browser Web Worker connecting Studio (`web/studio/`) to the `crates/uor-r4-integer`
// (`--features serving-wasm`) integer execution engine:
// `init`, `tickClock`, `loadStack`, `step`, `saveSession`, `restoreSession`,
// `weightsPerToken`, `allocEvents`, `leakedModels` (`crates/uor-r4-integer/src/wasm_bindgen_exports.rs`).
//
// Container family: the engine parses `uor-r4.lut-stack/1` .. `uor-r4.lut-stack/7`
// (`crates/uor-r4-integer/src/stack/format.rs`) and, since the M1 serving unit, the
// discrete `uor-r4.lut-discrete/1` artifact (`crates/uor-r4-integer/src/discrete_d11.rs`).
// The stack family is served as a stateful token session; the discrete family is
// served as stateless next-token prefix evaluation (the M1 model is a language base,
// not a chat model).
//
// Model sources: this worker is the only WASM backend in the Studio and it makes
// **no network calls**. The page resolves bytes for any source it offers
// (`bundled`, user `file`, user-initiated `url`, `api`) and posts them in
// `load_model`; the worker parses the header, optionally verifies
// `expectedSha256`, loads the session, and reports the provenance in
// `capabilities`. `engine_info` publishes the accepted schemas and sources, and
// `inspect_model` validates bytes without loading a session.
//
// Every capability field comes directly from the loaded `UORLUT01` header or the
// WASM exports. Prompt text is mapped to token IDs by the stack-bound ByteLevel BPE
// tokenizer artifact (`pkg/tokenizer.json`, generated by
// `web/studio/tools/make_tokenizer.mjs`, or the bundled
// `DEFAULT_STACK_TOKENIZER_ARTIFACT` when its `stack_sha256` and `vocab_size`
// match the loaded stack). When no matching stack-bound artifact is present, the
// worker falls back to the unbound byte-mod stand-in and labels it explicitly.

import {
    BYTE_BPE_MODE,
    DEFAULT_STACK_TOKENIZER_ARTIFACT,
    decodeTokenIdWithArtifact,
    encodeTextWithArtifact,
    sha256Hex,
    tokenizerLabel,
    validateTokenizerArtifact,
} from './uor_tokenizer_artifact.js';

const ENGINE_TAG = 'uor-r4-integer/serving-wasm';
const LUT_MAGIC = 'UORLUT01';
// The engine's container family: `uor-r4.lut-stack/1` .. `/7`, one schema per
// shape feature set (`crates/uor-r4-integer/src/stack/format.rs`).
const LUT_SCHEMA_PREFIX = 'uor-r4.lut-stack/';
const STACK_SCHEMA_MIN = 1;
const STACK_SCHEMA_MAX = 7;
// Served by the engine: /1-/7. A /7 stack carries the turn memory, served since the
// turn-memory-integer units 2-3 (`stack/session.rs`, `stack/memory.rs`).
const STACK_SERVED_MAX = 7;
const TURN_MEMORY_SCHEMA = 'uor-r4.lut-stack/7';
// Carried by the discrete runtime, which is native-only; the stack engine refuses it.
const DISCRETE_SCHEMA = 'uor-r4.lut-discrete/1';
const DISCRETE_TRUNK_SCHEMA = 'uor-r4.lut-discrete-trunk/1';
const ENGINE_SCHEMAS = Object.freeze(
    Array.from({ length: STACK_SCHEMA_MAX }, (_, i) => `${LUT_SCHEMA_PREFIX}${i + 1}`),
);
const SERVED_SCHEMAS = Object.freeze(
    Array.from({ length: STACK_SERVED_MAX }, (_, i) => `${LUT_SCHEMA_PREFIX}${i + 1}`),
);
// Where the page may have resolved the artifact bytes from. The worker itself
// makes no network requests: the page (or a desktop shell) owns resolution.
const MODEL_SOURCES = Object.freeze(['file', 'bundled', 'url', 'api']);
// The page's own artifact limit (128 MiB), enforced here as a second gate. The
// M1-closing 19-table trunk is 86.5 MB; the synthetic demo is 0.5 MB.
const MAX_ARTIFACT_BYTES = 128 * 1024 * 1024;
const MAX_SESSIONS = 32;

let wasmModule = null;
let wasmInitPromise = null;
let capabilities = null;
let tokenizerArtifact = null;
let activeHandle = null;
let activeDiscrete = null;
let initialSessionBytes = null;
let activeJob = null;
let latestLoadToken = 0;
const sessions = new Map();
const sessionEpochs = new Map();

function bumpSessionEpoch(conversationId) {
    if (!conversationId) return 0;
    const next = (sessionEpochs.get(conversationId) || 0) + 1;
    sessionEpochs.set(conversationId, next);
    return next;
}

async function ensureWasmLoaded() {
    if (!wasmInitPromise) {
        wasmInitPromise = (async () => {
            const mod = await import('../../pkg/uor_r4_integer.js');
            if (globalThis.__UOR_WASM_BYTES__) {
                await mod.default({ module_or_path: globalThis.__UOR_WASM_BYTES__ });
            } else {
                await mod.default();
            }
            wasmModule = mod;
            return mod;
        })().catch((error) => {
            wasmInitPromise = null;
            throw error;
        });
    }
    return wasmInitPromise;
}

function stackSchemaLevel(schema) {
    if (typeof schema !== 'string' || !schema.startsWith(LUT_SCHEMA_PREFIX)) return null;
    const level = Number(schema.slice(LUT_SCHEMA_PREFIX.length));
    return Number.isInteger(level) && level >= STACK_SCHEMA_MIN && level <= STACK_SCHEMA_MAX ? level : null;
}

function unsupportedSchemaReason(schema) {
    if (schema === DISCRETE_SCHEMA) {
        return `The ${DISCRETE_SCHEMA} container is not wired into the WASM serving engine yet ` +
            `(its discrete runtime is native-only). The stack engine parses ${LUT_SCHEMA_PREFIX}1..${STACK_SCHEMA_MAX} only.`;
    }
    return `Unsupported stack schema "${schema || 'unknown'}"; the stack engine parses ${LUT_SCHEMA_PREFIX}1..${STACK_SCHEMA_MAX} only.`;
}

function present(value) {
    return value !== undefined && value !== null;
}

function headerFeatures(parsed) {
    const shape = parsed.shape || {};
    return {
        pointer: present(shape.pointer),
        read_select: present(shape.read_select),
        hamming: present(parsed.hamming),
        turn_memory: present(parsed.memory),
        memory: present(shape.memory),
        projection: typeof shape.projection === 'string' ? shape.projection : 'dense-4bit',
        head: typeof shape.head === 'string' ? shape.head : 'dense-vocab',
        read: typeof shape.read === 'string' ? shape.read : 'dot',
        rec_gates: typeof shape.rec_gates === 'string' ? shape.rec_gates : 'table',
        gate: typeof shape.gate === 'string' ? shape.gate : 'table',
        raw_gates: Boolean(shape.raw_gates),
        raw_transition: Boolean(shape.raw_transition),
        transport_snap: present(parsed.transport_snap) ? String(parsed.transport_snap.name || 'unknown') : null,
    };
}

function statusLabelFor(schema, synthetic) {
    if (synthetic) return 'synthetic stand-in';
    return `unqualified stack artifact (${schema}; not a milestone-qualified model)`;
}

function parseUorLutHeader(bytes) {
    if (!(bytes instanceof Uint8Array) || bytes.byteLength < 16) {
        throw new Error('Expected a binary UORLUT01 stack file (at least 16 bytes).');
    }
    const magic = new TextDecoder('ascii').decode(bytes.subarray(0, 8));
    if (magic !== LUT_MAGIC) {
        throw new Error(`Unrecognized stack header magic "${magic}"; expected "${LUT_MAGIC}".`);
    }
    const view = new DataView(bytes.buffer, bytes.byteOffset, bytes.byteLength);
    const jsonLenBig = view.getBigUint64(8, true);
    const jsonLen = Number(jsonLenBig);
    if (!Number.isSafeInteger(jsonLen) || jsonLen <= 0 || 16 + jsonLen > bytes.byteLength) {
        throw new Error(`Invalid UORLUT01 header length (${jsonLen} bytes).`);
    }
    const headerJson = new TextDecoder('utf-8').decode(bytes.subarray(16, 16 + jsonLen));
    let parsed;
    try {
        parsed = JSON.parse(headerJson);
    } catch (error) {
        throw new Error(`UORLUT01 header is not valid JSON: ${error}`);
    }
    if (parsed && (parsed.schema === DISCRETE_SCHEMA || parsed.schema === DISCRETE_TRUNK_SCHEMA)) {
        const isTrunk = parsed.schema === DISCRETE_TRUNK_SCHEMA;
        const shape = parsed.shape || {};
        const vocabulary = Number(shape.vocabulary) || 0;
        const context = Number(shape.context) || 0;
        if (!vocabulary || !context || !parsed.shape || typeof parsed.shape !== 'object') {
            throw new Error('The discrete M1 header has no valid shape.vocabulary/context.');
        }
        return {
            schema: parsed.schema,
            schema_level: null,
            engine_kind: 'discrete',
            engine_supported: true,
            engine_support_reason: null,
            shape: {
                vocab: vocabulary,
                vocabulary,
                width: 0,
                heads: 0,
                mlp: 0,
                pattern: '',
                read: String(shape.read_mode || ''),
                rotation: false,
                context,
                blocks: Number(shape.blocks) || 0,
                kept_cells: Number(shape.kept_cells) || 0,
                stages: Number(shape.stages) || 0,
                seed: Number(shape.seed) || 0,
                epoch: Number(shape.epoch) || 0,
            },
            group: null,
            synthetic: false,
            status_label: isTrunk
                ? 'trained M1 model (19-table trunk, next-token prediction)'
                : 'M1 base export (4-table, next-token prediction)',
            features: headerFeatures(parsed),
            mode: 'discrete-prefix',
        };
    }
    const schemaLevel = stackSchemaLevel(parsed && parsed.schema);
    if (!Number.isInteger(schemaLevel)) {
        throw new Error(unsupportedSchemaReason(parsed && parsed.schema));
    }
    if (!parsed.shape || typeof parsed.shape !== 'object') {
        throw new Error(`Stack header ${parsed.schema} has no shape object.`);
    }
    const shape = parsed.shape;
    const synthetic = Boolean((parsed.source && parsed.source.synthetic === true) || parsed.synthetic === true);
    const vocab = Number(shape.vocab) || Number(shape.vocabulary) || 0;
    return {
        schema: parsed.schema,
        schema_level: schemaLevel,
        engine_kind: 'stack',
        engine_supported: schemaLevel <= STACK_SERVED_MAX,
        engine_support_reason: null,
        shape: {
            vocab,
            width: Number(shape.width) || 0,
            heads: Number(shape.heads) || 0,
            mlp: Number(shape.mlp) || 0,
            pattern: String(shape.pattern || ''),
            read: String(shape.read || ''),
            rotation: Boolean(shape.rotation),
            context: Number(shape.context) || 0,
        },
        group: typeof parsed.group === 'number' ? parsed.group : null,
        synthetic,
        status_label: statusLabelFor(parsed.schema, synthetic),
        features: headerFeatures(parsed),
    };
}

function requireModel() {
    if (!capabilities || activeHandle === null || !initialSessionBytes) {
        throw new Error('Load a UORLUT01 stack file (.lut / .bin) before generating. No model is bundled.');
    }
}

function ensureSessionEntry(conversationId) {
    requireModel();
    if (!conversationId) {
        throw new Error('A conversation identity is required.');
    }
    if (!sessions.has(conversationId)) {
        if (sessions.size >= MAX_SESSIONS) {
            throw new Error('32 sessions are open. Export and close an unused conversation.');
        }
        if (!sessionEpochs.has(conversationId)) {
            sessionEpochs.set(conversationId, 1);
        }
        sessions.set(conversationId, {
            bytes: new Uint8Array(initialSessionBytes),
            lastToken: null,
        });
    }
    return sessions.get(conversationId);
}

function cancelActive() {
    if (activeJob) {
        activeJob.cancelled = true;
    }
}

function encodePromptTokens(payload, vocabSize, artifact) {
    if (Array.isArray(payload.tokenIds) && payload.tokenIds.length > 0) {
        return payload.tokenIds.map((t) => {
            const id = Number(t);
            if (!Number.isInteger(id) || id < 0 || id >= vocabSize) {
                throw new Error(`Token ID ${t} is outside stack vocab range 0..${vocabSize - 1}.`);
            }
            return id;
        });
    }
    const userMessage = (payload.messages || []).filter((m) => m.role === 'user').pop();
    const rawPrompt = typeof payload.prompt === 'string'
        ? payload.prompt
        : (typeof userMessage?.content === 'string' ? userMessage.content : '');
    const text = rawPrompt.trim();
    if (!text) {
        throw new Error('A non-empty prompt or tokenIds array is required.');
    }
    return encodeTextWithArtifact(text, vocabSize, artifact);
}

function exactToolFromPayload(payload) {
    if (!wasmModule || typeof wasmModule.exactArithmetic !== 'function') return null;
    const userMessage = (payload.messages || []).filter((m) => m.role === 'user').pop();
    const prompt = typeof payload.prompt === 'string'
        ? payload.prompt
        : (typeof userMessage?.content === 'string' ? userMessage.content : '');
    if (!prompt.trim()) return null;
    const result = JSON.parse(wasmModule.exactArithmetic(prompt));
    if (result.error) throw new Error(result.error);
    return result.handled ? result : null;
}

function formatTokenChunk(tokenId, index, artifact, decodeText) {
    if (decodeText && artifact && artifact.mode === BYTE_BPE_MODE) {
        return decodeTokenIdWithArtifact(tokenId, artifact);
    }
    return index === 0 ? `${tokenId}` : ` ${tokenId}`;
}

async function loadTokenizerArtifact(stackBytes, headerInfo, payloadArtifact) {
    const sha = await sha256Hex(stackBytes);
    const vocab = headerInfo.shape && headerInfo.shape.vocab;
    if (payloadArtifact === false) {
        return null;
    }
    if (payloadArtifact && validateTokenizerArtifact(payloadArtifact, sha, vocab)) {
        return payloadArtifact;
    }
    try {
        const mod = await import('../../pkg/tokenizer.json', { with: { type: 'json' } });
        const artifact = mod.default || mod;
        if (validateTokenizerArtifact(artifact, sha, vocab)) {
            return artifact;
        }
    } catch (_error) {
        // Fall through to bundled default artifact check.
    }
    if (validateTokenizerArtifact(DEFAULT_STACK_TOKENIZER_ARTIFACT, sha, vocab)) {
        return DEFAULT_STACK_TOKENIZER_ARTIFACT;
    }
    return null;
}

function toBytes(value) {
    if (value instanceof Uint8Array) return value;
    return new Uint8Array(value || []);
}

// The page names the source it resolved the bytes from; the worker never resolves
// one itself. `sourceLabel` is display-only (control characters stripped, capped).
function normalizeSource(payload) {
    const requested = typeof payload.source === 'string'
        ? payload.source.toLowerCase()
        : (payload.bundled === true ? 'bundled' : 'file');
    const source = MODEL_SOURCES.includes(requested) ? requested : 'file';
    const label = typeof payload.sourceLabel === 'string'
        ? payload.sourceLabel.replace(/[\u0000-\u001f\u007f]/g, ' ').trim().slice(0, 160)
        : '';
    return { source, source_label: label || null };
}

// An optional binding: `expectedSha256` directly, or the `sha256` of a bundled
// manifest. Malformed values are ignored (the artifact is then reported unbound).
function expectedSha256Of(payload) {
    const raw = payload.expectedSha256 ?? (payload.manifest && payload.manifest.sha256);
    if (typeof raw !== 'string') return null;
    const normalized = raw.trim().toLowerCase();
    return /^[0-9a-f]{64}$/.test(normalized) ? normalized : null;
}

self.onmessage = async ({ data }) => {
    const { action, id, payload = {} } = data || {};
    const loadToken = action === 'load_model' ? ++latestLoadToken : null;
    try {
        if (action === 'cancel' || action === 'stop_generation') {
            cancelActive();
            return;
        }
        if (action === 'get_storage_status') {
            const storage = self.navigator?.storage?.estimate
                ? await self.navigator.storage.estimate()
                : null;
            self.postMessage({
                action: 'storage_status_result',
                storage: storage
                    ? {
                        usageMB: (storage.usage / 1048576).toFixed(1),
                        quotaMB: (storage.quota / 1048576).toFixed(1),
                    }
                    : null,
            });
            return;
        }
        if (action === 'purge_all_caches') {
            throw new Error('The loaded stack is held in worker memory. Reload the page to unload it; saved conversations are preserved.');
        }
        if (action === 'prewarm') {
            await ensureWasmLoaded();
            self.postMessage({
                action: 'runtime_loaded',
                engine: ENGINE_TAG,
                ready: Boolean(capabilities),
                capabilities,
                parse_schemas: ENGINE_SCHEMAS,
                served_schemas: SERVED_SCHEMAS,
                refused_schemas: [],
                turn_memory_served: true,
                discrete_supported: false,
            });
            return;
        }
        if (action === 'engine_info') {
            // Static engine limits; does not import the WASM module or touch a model.
            self.postMessage({
                action: 'engine_info_result',
                id,
                engine: ENGINE_TAG,
                parse_schemas: ENGINE_SCHEMAS,
                served_schemas: SERVED_SCHEMAS,
                refused_schemas: [],
                turn_memory_served: true,
                discrete_schemas: [DISCRETE_SCHEMA],
                discrete_supported: true,
                discrete_engine: 'uor-r4-integer/discrete (stateless next-token prefix prediction)',
                load_sources: MODEL_SOURCES,
                max_artifact_bytes: MAX_ARTIFACT_BYTES,
                wasm_loaded: Boolean(wasmModule),
                network: 'The worker performs no network requests; the page resolves bundled/file/url/api bytes and posts them here.',
                tokenizer: 'optional stack-bound byte-bpe tokenizer artifact; unbound byte-mod stand-in when absent or mismatched',
            });
            return;
        }
        if (action === 'inspect_model') {
            // Header parse and digest only: no session, no leaked model.
            const raw = toBytes(payload.bytes);
            if (!raw.byteLength) {
                throw new Error('inspect_model needs the artifact bytes.');
            }
            const headerInfo = parseUorLutHeader(raw);
            const sha256 = await sha256Hex(raw);
            self.postMessage({
                action: 'model_inspected',
                id,
                artifact_bytes: raw.byteLength,
                artifact_sha256: sha256,
                header: headerInfo,
            });
            return;
        }
        if (action === 'load_model') {
            if (activeJob) {
                throw new Error('Stop generation before loading a stack artifact.');
            }
            capabilities = null;
            tokenizerArtifact = null;
            activeHandle = null;
            activeDiscrete = null;
            initialSessionBytes = null;
            sessions.clear();
            sessionEpochs.clear();
            await ensureWasmLoaded();
            if (loadToken !== latestLoadToken) return;
            const raw = toBytes(payload.bytes);
            if (!raw.byteLength) {
                throw new Error('The selected stack artifact is empty.');
            }
            if (raw.byteLength > MAX_ARTIFACT_BYTES) {
                throw new Error(`The stack artifact is ${raw.byteLength} bytes; the browser load limit is ${MAX_ARTIFACT_BYTES} bytes.`);
            }
            const manifest = payload.manifest && typeof payload.manifest === 'object' ? payload.manifest : null;
            if (manifest && Number.isInteger(manifest.size) && manifest.size !== raw.byteLength) {
                throw new Error(`Artifact size ${raw.byteLength} does not match the manifest size ${manifest.size}.`);
            }
            const headerInfo = parseUorLutHeader(raw);
            const artifactSha256 = await sha256Hex(raw);
            if (loadToken !== latestLoadToken) return;
            const expectedSha256 = expectedSha256Of(payload);
            if (expectedSha256 && artifactSha256 !== expectedSha256) {
                throw new Error(`Artifact sha256 ${artifactSha256} does not match the expected ${expectedSha256}; refusing to load.`);
            }
            const { source, source_label } = normalizeSource(payload);
            const nextTokenizerArtifact = await loadTokenizerArtifact(raw, headerInfo, payload.tokenizerArtifact);
            if (loadToken !== latestLoadToken) return;
            if (headerInfo.engine_kind === 'discrete') {
                const handle = wasmModule.loadDiscrete(raw);
                tokenizerArtifact = nextTokenizerArtifact;
                activeDiscrete = handle;
                activeHandle = null;
                initialSessionBytes = null;
                sessions.clear();
                sessionEpochs.clear();
                capabilities = {
                    engine: 'uor-r4-integer/discrete',
                    mode: 'discrete-prefix',
                    handle,
                    file_name: payload.fileName
                        || (manifest && typeof manifest.name === 'string' ? manifest.name : null),
                    artifact_bytes: raw.byteLength,
                    artifact_sha256: artifactSha256,
                    expected_sha256: expectedSha256,
                    sha256_verified: expectedSha256 ? true : null,
                    source,
                    source_label,
                    schema: headerInfo.schema,
                    engine_supported: true,
                    shape: headerInfo.shape,
                    features: headerInfo.features,
                    synthetic: false,
                    status_label: headerInfo.status_label,
                    tokenizer_label: tokenizerLabel(nextTokenizerArtifact, headerInfo.shape.vocab),
                    weights_per_token: null,
                    checkpoint_bytes: null,
                    can_generate: false,
                    can_predict: true,
                    alloc_events: Number(wasmModule.allocEvents()),
                    leaked_models: Number(wasmModule.leakedModels()),
                };
                self.postMessage({
                    action: 'model_loaded',
                    id,
                    capabilities,
                    bytes: raw.byteLength,
                    schema: headerInfo.schema,
                    sha256: artifactSha256,
                    source,
                });
                return;
            }
            wasmModule.tickClock(1n);
            const handle = wasmModule.loadStack(raw);
            const blankState = wasmModule.saveSession(handle);
            const wpt = Number(wasmModule.weightsPerToken(handle));
            const allocCount = Number(wasmModule.allocEvents());
            const leaked = Number(wasmModule.leakedModels());
            let turnMemory = null;
            try {
                turnMemory = wasmModule.memoryInfo ? JSON.parse(wasmModule.memoryInfo(handle)) : null;
            } catch (_error) {
                turnMemory = null;
            }
            const hasTurnMemory = Boolean(turnMemory && turnMemory.present);

            tokenizerArtifact = nextTokenizerArtifact;
            activeHandle = handle;
            activeDiscrete = null;
            initialSessionBytes = new Uint8Array(blankState);
            sessions.clear();
            sessionEpochs.clear();

            capabilities = {
                engine: ENGINE_TAG,
                handle,
                file_name: payload.fileName
                    || (manifest && typeof manifest.name === 'string' ? manifest.name : null),
                artifact_bytes: raw.byteLength,
                artifact_sha256: artifactSha256,
                expected_sha256: expectedSha256,
                sha256_verified: expectedSha256 ? true : null,
                source,
                source_label,
                schema: headerInfo.schema,
                schema_level: headerInfo.schema_level,
                engine_supported: headerInfo.engine_supported,
                shape: headerInfo.shape,
                features: headerInfo.features,
                group: headerInfo.group,
                synthetic: headerInfo.synthetic,
                status_label: headerInfo.status_label,
                tokenizer_label: tokenizerLabel(nextTokenizerArtifact, headerInfo.shape.vocab),
                weights_per_token: wpt,
                checkpoint_bytes: initialSessionBytes.byteLength,
                turn_memory: turnMemory,
                can_restore_session: !hasTurnMemory,
                can_export_session: !hasTurnMemory,
                alloc_events: allocCount,
                leaked_models: leaked,
            };

            self.postMessage({
                action: 'model_loaded',
                id,
                capabilities,
                bytes: raw.byteLength,
                schema: headerInfo.schema,
                sha256: artifactSha256,
                source,
            });
            return;
        }

        if (action === 'predict_discrete') {
            if (activeDiscrete === null) {
                throw new Error('Load the M1 discrete model before predicting; the loaded model is not a discrete artifact.');
            }
            const context = capabilities && capabilities.shape ? Number(capabilities.shape.context) : 0;
            const vocab = capabilities && capabilities.shape ? Number(capabilities.shape.vocab) : 0;
            const ids = Array.isArray(payload.tokenIds) ? payload.tokenIds.map((v) => Number(v)) : [];
            if (!ids.length) {
                throw new Error('predict_discrete needs a non-empty tokenIds prompt.');
            }
            if (context > 0 && ids.length > context) {
                throw new Error(`The M1 model serves prefixes up to ${context} tokens; got ${ids.length}.`);
            }
            if (vocab > 0 && ids.some((id) => !Number.isInteger(id) || id < 0 || id >= vocab)) {
                throw new Error(`A prompt token id is outside the model vocabulary (0..${vocab - 1}).`);
            }
            const started = performance.now();
            const prediction = JSON.parse(wasmModule.predictDiscrete(activeDiscrete, Uint32Array.from(ids)));
            const durationMs = performance.now() - started;
            const decoded = (prediction.top8 || []).map((id) => ({
                id,
                text: decodeTokenIdWithArtifact(id, tokenizerArtifact),
            }));
            self.postMessage({
                action: 'discrete_prediction_result',
                id,
                schema: prediction.schema,
                artifact_sha256: prediction.artifact_sha256,
                prediction: prediction.prediction,
                top8: prediction.top8,
                decoded,
                admitted_cells: prediction.admitted_cells,
                prompt_tokens: prediction.prompt_tokens,
                vocabulary: prediction.vocabulary,
                context: prediction.context,
                durationMs,
                tokenizer_label: capabilities ? capabilities.tokenizer_label : null,
            });
            return;
        }

        if (action !== 'generate') {
            requireModel();
        }

        if (action === 'close_session' || action === 'reset_session') {
            if (activeJob) {
                throw new Error('Stop generation before closing or resetting a session.');
            }
            if (capabilities && capabilities.turn_memory && capabilities.turn_memory.present) {
                throw new Error('A turn-memory stack keeps its turn state in the session: reload the model to start again (its turn state is not saved yet).');
            }
            const convId = payload.conversationId;
            if (convId) {
                sessions.delete(convId);
                bumpSessionEpoch(convId);
            }
            wasmModule.restoreSession(activeHandle, initialSessionBytes);
            self.postMessage({
                action: 'session_reset',
                id,
                conversationId: convId,
            });
            return;
        }

        if (action === 'export_session') {
            if (capabilities && capabilities.turn_memory && capabilities.turn_memory.present) {
                throw new Error('A turn-memory session checkpoint cannot be restored yet (its turn state is not saved): reload the model instead.');
            }
            if (activeJob) {
                throw new Error('Stop generation before exporting a session checkpoint.');
            }
            const entry = ensureSessionEntry(payload.conversationId);
            self.postMessage({
                action: 'session_exported',
                id,
                conversationId: payload.conversationId,
                bytes: new Uint8Array(entry.bytes),
                lastToken: entry.lastToken,
            });
            return;
        }

        if (action === 'import_session') {
            if (capabilities && capabilities.turn_memory && capabilities.turn_memory.present) {
                throw new Error('A turn-memory session checkpoint cannot be imported yet (its turn state is not saved): reload the model instead.');
            }
            if (activeJob) {
                throw new Error('Stop generation before importing a session checkpoint.');
            }
            const convId = payload.conversationId;
            if (!convId) {
                throw new Error('A conversation identity is required to import a checkpoint.');
            }
            const rawCheckpoint = payload.bytes instanceof Uint8Array
                ? payload.bytes
                : new Uint8Array(payload.bytes || []);
            if (!rawCheckpoint.byteLength) {
                throw new Error('Checkpoint payload is empty.');
            }
            wasmModule.restoreSession(activeHandle, rawCheckpoint);
            const verifiedBytes = wasmModule.saveSession(activeHandle);
            bumpSessionEpoch(convId);
            sessions.set(convId, {
                bytes: new Uint8Array(verifiedBytes),
                lastToken: typeof payload.lastToken === 'number' ? payload.lastToken : null,
            });
            self.postMessage({
                action: 'session_imported',
                id,
                conversationId: convId,
                bytes: verifiedBytes.byteLength,
            });
            return;
        }

        if (action !== 'generate') {
            throw new Error(`Unknown worker action: ${action}`);
        }
        if (activeDiscrete !== null) {
            throw new Error('The M1 discrete model serves next-token prediction only: use Predict for a prefix, or load a stack artifact (synthetic demo, local file or URL) to generate.');
        }
        if (activeJob) {
            throw new Error('Another generation is active. Wait for its completion or cancellation.');
        }

        const exactTool = exactToolFromPayload(payload);
        if (exactTool) {
            const started = performance.now();
            const job = { id, cancelled: false };
            activeJob = job;
            try {
                self.postMessage({
                    action: 'stream_token',
                    id,
                    chunk: exactTool.text,
                    fullText: exactTool.text,
                    tokenCount: 0,
                    tps: null,
                    tool: 'm6-exact-arithmetic',
                });
                const durationSec = (performance.now() - started) / 1000;
                self.postMessage({
                    action: 'generate_complete',
                    id,
                    fullText: exactTool.text,
                    tokenIds: [],
                    tokenCount: 0,
                    durationSec,
                    tps: null,
                    stoppedBy: 'tool',
                    tool: 'm6-exact-arithmetic',
                    statusLabel: 'exact arithmetic tool',
                    tokenizerLabel: 'R4 geometric decimal place-value tool',
                });
            } finally {
                if (activeJob === job) activeJob = null;
            }
            return;
        }

        const hasTurnMemory = Boolean(capabilities && capabilities.turn_memory && capabilities.turn_memory.present);
        const convId = payload.conversationId || 'default';
        const entry = hasTurnMemory ? null : ensureSessionEntry(convId);
        const startEpoch = sessionEpochs.get(convId) || 1;
        if (!hasTurnMemory) {
            wasmModule.restoreSession(activeHandle, entry.bytes);
        }

        const decodeText = !Array.isArray(payload.tokenIds) || payload.tokenIds.length === 0;
        const promptTokens = encodePromptTokens(payload, capabilities.shape.vocab, tokenizerArtifact);
        const maxTokens = Math.min(4096, Math.max(1, Number(payload.options?.max_new_tokens) || 32));
        const job = { id, conversationId: convId, epoch: startEpoch, cancelled: false };
        activeJob = job;

        const started = performance.now();
        try {
            let tok = promptTokens[0];
            for (let i = 1; i < promptTokens.length; i++) {
                wasmModule.tickClock(1n);
                wasmModule.step(activeHandle, tok);
                tok = promptTokens[i];
            }

            if (hasTurnMemory) {
                wasmModule.markReplyStart(activeHandle);
            }

            const allocBefore = wasmModule.allocEvents();
            const tokenIds = [];
            let fullText = '';

            for (let stepIdx = 0; stepIdx < maxTokens && !job.cancelled; stepIdx++) {
                if (!hasTurnMemory && ((sessionEpochs.get(convId) || 0) !== startEpoch || !sessions.has(convId))) {
                    job.cancelled = true;
                    break;
                }
                wasmModule.tickClock(1n);
                const [nextTok, marginQ16, stepCount] = wasmModule.step(activeHandle, tok);
                tok = nextTok;
                tokenIds.push(tok);
                const chunk = formatTokenChunk(tok, stepIdx, tokenizerArtifact, decodeText);
                fullText += chunk;

                const durationSec = (performance.now() - started) / 1000;
                self.postMessage({
                    action: 'stream_token',
                    id,
                    chunk,
                    fullText,
                    tokenId: tok,
                    marginQ16,
                    stepCount,
                    tokenCount: tokenIds.length,
                    tps: durationSec > 0 ? tokenIds.length / durationSec : null,
                });

                if ((stepIdx + 1) % 8 === 0) {
                    await new Promise((resolvePromise) => setTimeout(resolvePromise, 0));
                }
            }

            const allocAfter = wasmModule.allocEvents();
            const allocDelta = Number(allocAfter - allocBefore);
            if (!hasTurnMemory && (sessionEpochs.get(convId) || 0) === startEpoch && sessions.has(convId)) {
                const savedBytes = wasmModule.saveSession(activeHandle);
                sessions.set(convId, {
                    bytes: new Uint8Array(savedBytes),
                    lastToken: tok,
                });
            }

            capabilities.alloc_events = Number(allocAfter);
            capabilities.leaked_models = Number(wasmModule.leakedModels());

            const durationSec = (performance.now() - started) / 1000;
            const stoppedBy = job.cancelled ? 'cancelled' : 'length';
            self.postMessage({
                action: 'generate_complete',
                id,
                fullText,
                tokenIds,
                tokenCount: tokenIds.length,
                durationSec,
                tps: durationSec > 0 ? tokenIds.length / durationSec : null,
                stoppedBy,
                weightsPerToken: capabilities.weights_per_token,
                allocDelta,
                allocEvents: capabilities.alloc_events,
                statusLabel: capabilities.status_label,
                tokenizerLabel: capabilities.tokenizer_label,
            });
        } finally {
            if (activeJob === job) {
                activeJob = null;
            }
        }
    } catch (error) {
        if (action === 'load_model' && loadToken !== latestLoadToken) return;
        self.postMessage({
            action: action === 'generate' ? 'generate_error' : 'operation_error',
            id,
            operation: action,
            error: String(error),
        });
    }
};
