pub fn sha256_hex(bytes: &[u8]) -> String {
    let mut hasher = Sha256::new();
    hasher.update(bytes);
    format!("{:x}", hasher.finalize())
}

pub fn candidate_root_image(base_root: usize, candidate: usize) -> Option<usize> {
    if candidate >= 16 {
        return None;
    }
    match base_root {
        0 => Some(ROOT0_CANDIDATE_ROOTS[candidate]),
        1 => Some(ROOT1_CANDIDATE_ROOTS[candidate]),
        2 => Some(ROOT2_CANDIDATE_ROOTS[candidate]),
        3 => Some(ROOT3_CANDIDATE_ROOTS[candidate]),
        15 => Some(ROOT15_CANDIDATE_ROOTS[candidate]),
        _ => None,
    }
}

pub fn write_token_blocks(table: &mut [i32], token: usize, block_roots: [usize; 4]) {
    let base = token * 32;
    for (block, &root_idx) in block_roots.iter().enumerate() {
        let dst = base + block * 8;
        table[dst..dst + 8].copy_from_slice(&ROOTS[root_idx]);
    }
}

/// C-R1 Variant 1A-i: 16 tokens, 4 blocks, occupied cells `{0, 2, 15, 32, 255}` with
/// mixed distances `[(0, 0), (4, 2), (4, 15), (4, 32), (8, 255)]` relative to `q = [r0, r0, r0, r0]`.
pub fn c_r1_mixed_distance_table() -> Vec<i32> {
    let mut table = vec![0i32; 16 * 32];
    write_token_blocks(&mut table, 0, [0, 0, 0, 0]); // cell 0, d = 0
    write_token_blocks(&mut table, 1, [0, 0, 0, 2]); // cell 2, d = 4
    write_token_blocks(&mut table, 2, [0, 0, 0, 15]); // target cell 15, d = 4
    write_token_blocks(&mut table, 3, [2, 0, 0, 0]); // cell 32, d = 4
    for tok in 4..16 {
        write_token_blocks(&mut table, tok, [15, 0, 0, 15]); // cell 255, d = 8
    }
    table
}

/// C-R1 Variant 1A-ii: 16 tokens, 4 blocks, occupied cells `{0, 1, 15, 16, 255}` (`objective.rs:87`)
/// all at equal distance `d = 16` relative to `q = [r3, r3, r3, r3]` (`routes = [0, 42, 0, 42, 0, 42, 0, 42]`).
pub fn c_r1_equal_distance_tie_table() -> Vec<i32> {
    let mut table = vec![0i32; 16 * 32];
    write_token_blocks(&mut table, 0, [0, 0, 0, 0]); // cell 0, d = 16
    write_token_blocks(&mut table, 1, [0, 0, 0, 1]); // cell 1, d = 16
    write_token_blocks(&mut table, 2, [0, 0, 0, 15]); // target cell 15, d = 16
    write_token_blocks(&mut table, 3, [1, 0, 0, 0]); // cell 16, d = 16
    for tok in 4..16 {
        write_token_blocks(&mut table, tok, [15, 0, 0, 15]); // cell 255, d = 16
    }
    table
}

pub fn c_r1_equal_distance_routes() -> Vec<u32> {
    vec![0, 42, 0, 42, 0, 42, 0, 42]
}

/// C-R1 Fixture 1B: 256 tokens occupying all 256 cells `c = a * 16 + b` (`objective.rs:90`).
/// Context `[token 34]` (`cell 34 = (r2, r2)`), target `token 255` (`cell 255 = (r15, r15)`).
pub fn c_r1_all_256_cells_table() -> Vec<i32> {
    let mut table = vec![0i32; 256 * 32];
    for cell in 0..256usize {
        let a = cell / 16;
        let b = cell % 16;
        write_token_blocks(&mut table, cell, [a, 2, 2, b]);
    }
    table
}

/// C-R2 Part 2A: crowd rival `cell 1` (`objective.rs:95`) with `multiplicity` in `{1, 2, 4}` tokens
/// by reassigning `multiplicity - 1` spare tokens from `cell 255` into `cell 1`.
pub fn c_r2_crowded_rival_cell_table(multiplicity: usize) -> Vec<i32> {
    assert!(matches!(multiplicity, 1 | 2 | 4));
    let mut table = c_r1_equal_distance_tie_table();
    for extra in 0..(multiplicity - 1) {
        write_token_blocks(&mut table, 4 + extra, [0, 0, 0, 1]);
    }
    table
}

/// C-R2 Part 2B: move `token 4` from `cell 255` into newly occupied preceding `cell 2` (`objective.rs:97`).
pub fn c_r2_new_preceding_cell_table() -> Vec<i32> {
    let mut table = c_r1_equal_distance_tie_table();
    write_token_blocks(&mut table, 4, [0, 0, 0, 2]);
    table
}

/// C-R3 base table for `empty_cell`: occupied cells `{0, 1, 15, 31, 255}` where `token 3` is the
/// sole occupant of `cell 31 = [r1, r0, r0, r15]`. Mutating `token 3` block 0 via candidate 7 or 15
/// maps `r1 -> r15`, moving `token 3` into already-occupied `cell 255` and reducing `occupied_cells`
/// from `5` to `4`.
pub fn c_r3_empty_cell_base_table() -> Vec<i32> {
    let mut table = c_r1_equal_distance_tie_table();
    write_token_blocks(&mut table, 3, [1, 0, 0, 15]);
    table
}

/// C-R4 Fixture 4A-i: all 16 tokens in a single occupied `cell 0` (`occupied_cells == 1`, `K = 16`).
pub fn c_r4_single_occupied_cell_table() -> Vec<i32> {
    let mut table = vec![0i32; 16 * 32];
    for tok in 0..16usize {
        write_token_blocks(&mut table, tok, [0, tok % 16, (tok * 3) % 16, 0]);
    }
    table
}

/// C-R4 Fixture 4A-ii: 16 tokens in 16 distinct occupied cells `0..16` (`occupied_cells == 16`, `K = 16`).
pub fn c_r4_sixteen_occupied_cells_table() -> Vec<i32> {
    let mut table = vec![0i32; 16 * 32];
    for tok in 0..16usize {
        write_token_blocks(&mut table, tok, [0, 0, 0, tok]);
    }
    table
}

/// C-R4 Fixture 4B: 16 tokens at `K = 1` where `cell 0` contains only `token 0` (`admitted_token_count = 1`),
/// and `tokens 1..16` reside in `cell 255`. For `target = 0`, `token_rivals == 0` (ineligible);
/// for `target = 1`, `token_rivals == 1` (eligible).
pub fn c_r4_absent_rival_table() -> Vec<i32> {
    let mut table = vec![0i32; 16 * 32];
    write_token_blocks(&mut table, 0, [0, 0, 0, 0]); // sole token in admitted cell 0
    for tok in 1..16usize {
        write_token_blocks(&mut table, tok, [15, tok % 16, 0, 15]); // cell 255
    }
    table
}

