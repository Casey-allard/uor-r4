//! Build for the D11 artifact scorer instrument (claude-116).
//!
//! 1. The fixed geometry tables (AXES, COMPOSE, ROOTS, BFS, BRANCH) are read
//!    from the clean-room integer evaluator's own source,
//!    `crates/uor-r4-integer/src/discrete_d11.rs`, and written to
//!    `OUT_DIR/d11_tables.h`, so the kernel cannot drift from the reference.
//! 2. `src/kernel_core.h` is compiled as host C++ (`src/host_kernel.cpp`) for
//!    the finite parity tests against `IntegerDiscreteModel` only.
//! 3. With the `cuda` feature, `src/scorer.cu` is compiled ahead of time by
//!    nvcc to PTX, admitted by the same integer PTX rules as
//!    `crates/uor-r4-discrete/build.rs`, and assembled to a cubin. No NVRTC.
use std::{env, fs, path::PathBuf, process::Command};

const REFERENCE: &str = "../../../../crates/uor-r4-integer/src/discrete_d11.rs";
const ENTRIES: [&str; 1] = ["d11_score_rows"];

/// The integers of one `const NAME: TYPE = [ ... ];` literal in the reference.
fn table(source: &str, name: &str, expected: usize) -> Result<Vec<i64>, String> {
    let head = format!("const {name}:");
    let start = source
        .lines()
        .position(|line| line.starts_with(&head))
        .ok_or_else(|| format!("reference table {name} not found"))?;
    let mut text = String::new();
    for line in source.lines().skip(start) {
        text.push_str(line);
        text.push('\n');
        if line.trim_end() == "];" {
            break;
        }
    }
    let body = text
        .split_once("= [")
        .map(|(_, body)| body)
        .ok_or_else(|| format!("reference table {name} has no literal"))?;
    let values = body
        .split(|c: char| !(c.is_ascii_digit() || c == '-'))
        .filter(|token| !token.is_empty())
        .map(|token| {
            token
                .parse::<i64>()
                .map_err(|e| format!("{name}: {token}: {e}"))
        })
        .collect::<Result<Vec<_>, _>>()?;
    if values.len() != expected {
        return Err(format!(
            "reference table {name} has {} values, expected {expected}",
            values.len()
        ));
    }
    Ok(values)
}

/// A C array initializer; `row` > 0 groups the values into rows of that width.
fn c_array(ty: &str, name: &str, dims: &str, values: &[i64], row: usize) -> String {
    let join = |chunk: &[i64]| {
        chunk
            .iter()
            .map(i64::to_string)
            .collect::<Vec<_>>()
            .join(", ")
    };
    let body = if row == 0 {
        join(values)
    } else {
        values
            .chunks(row)
            .map(|chunk| format!("{{{}}}", join(chunk)))
            .collect::<Vec<_>>()
            .join(", ")
    };
    format!("D11_CONST {ty} {name}{dims} = {{{body}}};\n")
}

fn tables_header() -> Result<String, String> {
    let source = fs::read_to_string(REFERENCE).map_err(|e| format!("{REFERENCE}: {e}"))?;
    let axes = table(&source, "AXES", 512)?;
    let compose = table(&source, "COMPOSE", 4096)?;
    let roots = table(&source, "ROOTS", 128)?;
    let bfs = table(&source, "BFS", 256)?;
    let branch = table(&source, "BRANCH", 48)?;
    if axes
        .iter()
        .chain(&compose)
        .chain(&bfs)
        .chain(&branch)
        .any(|v| !(0..=255).contains(v))
        || roots.iter().any(|v| !(-128..=127).contains(v))
    {
        return Err("a reference table value is outside its storage type".into());
    }
    let mut header = String::from(
        "// Generated by build.rs from crates/uor-r4-integer/src/discrete_d11.rs.\n\
         #ifndef D11_TABLES_H\n#define D11_TABLES_H\n#include <stdint.h>\n",
    );
    header.push_str(&c_array("uint8_t", "D11_AXES", "[512]", &axes, 0));
    header.push_str(&c_array("uint8_t", "D11_COMPOSE", "[4096]", &compose, 0));
    header.push_str(&c_array("int8_t", "D11_ROOTS", "[16][8]", &roots, 8));
    header.push_str(&c_array("uint8_t", "D11_BFS", "[256]", &bfs, 0));
    header.push_str(&c_array("uint8_t", "D11_BRANCH", "[16][3]", &branch, 3));
    header.push_str("#endif\n");
    Ok(header)
}

/// Mirrors `admit_ptx_inventory` in `crates/uor-r4-discrete/build.rs`: inspect
/// the emitted module, not the CUDA spelling. Integer index products are not
/// prohibited.
fn admit_ptx(ptx: &str, inventory: &[&str]) -> Result<(), String> {
    let mut entries = std::collections::BTreeSet::new();
    let mut expect_entry = false;
    for (line_number, line) in ptx.lines().enumerate() {
        let instruction = line.split("//").next().unwrap_or_default();
        for token in instruction
            .split(|c: char| !(c.is_ascii_alphanumeric() || c == '_' || c == '.'))
            .filter(|token| !token.is_empty())
        {
            let components: Vec<_> = token.split('.').collect();
            if components.iter().any(|component| {
                matches!(
                    *component,
                    "f16"
                        | "f16x2"
                        | "f32"
                        | "f64"
                        | "bf16"
                        | "bf16x2"
                        | "tf32"
                        | "e4m3"
                        | "e5m2"
                        | "mma"
                        | "wmma"
                        | "wgmma"
                        | "tcgen05"
                        | "tensor"
                        | "tensormap"
                )
            }) || token.starts_with("ex2.approx")
            {
                return Err(format!(
                    "integer PTX admission rejected {token} at line {}",
                    line_number + 1
                ));
            }
            if expect_entry {
                if token.contains('.') || !entries.insert(token.to_owned()) {
                    return Err(format!("invalid or duplicate PTX entry {token}"));
                }
                expect_entry = false;
            } else if token == ".entry" {
                expect_entry = true;
            }
        }
    }
    if expect_entry {
        return Err("unterminated PTX entry declaration".into());
    }
    let expected: std::collections::BTreeSet<_> =
        inventory.iter().map(|entry| entry.to_string()).collect();
    if entries != expected {
        return Err(format!(
            "integer PTX entry inventory differs: missing {:?}, unexpected {:?}",
            expected.difference(&entries).collect::<Vec<_>>(),
            entries.difference(&expected).collect::<Vec<_>>()
        ));
    }
    Ok(())
}

// Lexer controls only; these strings are never loaded or run.
fn ptx_admission_self_test() -> Result<(), String> {
    let inventory = ENTRIES
        .iter()
        .map(|entry| format!(".visible .entry {entry}() {{ ret; }}\n"))
        .collect::<String>();
    admit_ptx(
        &format!("// floats such as .f32 are comments\n{inventory}mul.lo.u32 %a,%b,8;"),
        &ENTRIES,
    )?;
    for forbidden in [
        "add.f32 %a,%b,%c;",
        ".reg .bf16 %a;",
        "mma.sync.aligned.m16n8k8.row.col.s32.s8.s8.s32 %a,%b,%c,%d;",
        "ex2.approx %a,%b;",
        ".visible .entry unexpected() { ret; }",
        ".visible .entry d11_score_rows() { ret; }",
    ] {
        if admit_ptx(&format!("{inventory}{forbidden}"), &ENTRIES).is_ok() {
            return Err(format!(
                "PTX admission self-test failed to reject {forbidden}"
            ));
        }
    }
    if admit_ptx("", &ENTRIES).is_ok() {
        return Err("PTX admission self-test failed to reject missing entries".into());
    }
    Ok(())
}

fn main() -> Result<(), Box<dyn std::error::Error>> {
    println!("cargo:rerun-if-changed=build.rs");
    println!("cargo:rerun-if-changed={REFERENCE}");
    println!("cargo:rerun-if-changed=src/kernel_core.h");
    println!("cargo:rerun-if-changed=src/host_kernel.cpp");
    println!("cargo:rerun-if-changed=src/scorer.cu");
    println!("cargo:rerun-if-env-changed=NVCC");
    println!("cargo:rerun-if-env-changed=UOR_NVCC_ARCH");
    let out = PathBuf::from(env::var_os("OUT_DIR").ok_or("Cargo did not supply OUT_DIR")?);
    ptx_admission_self_test()?;
    fs::write(out.join("d11_tables.h"), tables_header()?)?;

    cc::Build::new()
        .cpp(true)
        .std("c++17")
        .include(&out)
        .include("src")
        .warnings(true)
        .file("src/host_kernel.cpp")
        .compile("d11_host_kernel");

    if env::var_os("CARGO_FEATURE_CUDA").is_none() {
        return Ok(());
    }
    let arch = env::var("UOR_NVCC_ARCH")
        .map_err(|_| "CUDA build requires the explicit admitted UOR_NVCC_ARCH")?;
    if !arch
        .strip_prefix("compute_")
        .is_some_and(|digits| !digits.is_empty() && digits.bytes().all(|c| c.is_ascii_digit()))
    {
        return Err("UOR_NVCC_ARCH must be compute_<decimal capability>".into());
    }
    let nvcc = env::var("NVCC").unwrap_or_else(|_| "nvcc".into());
    let ptx = out.join("d11_scorer.ptx");
    let status = Command::new(&nvcc)
        .args(["-ptx", "-std=c++17"])
        .arg(format!("-arch={arch}"))
        .arg("-I")
        .arg(&out)
        .arg("-I")
        .arg("src")
        .arg("-o")
        .arg(&ptx)
        .arg("src/scorer.cu")
        .status()?;
    if !status.success() {
        return Err(format!("ahead-of-time nvcc scorer build failed: {status}").into());
    }
    admit_ptx(&fs::read_to_string(&ptx)?, &ENTRIES)?;
    // Assemble the admitted PTX, rather than compiling the source again.
    let image_target = arch.replacen("compute_", "sm_", 1);
    let report = Command::new(&nvcc)
        .args(["-cubin", "--ptxas-options=-v"])
        .arg(format!("-arch={arch}"))
        .arg(format!("--gpu-code={image_target}"))
        .arg("-o")
        .arg(out.join("d11_scorer.cubin"))
        .arg(&ptx)
        .output()?;
    let mut log = report.stdout;
    log.extend(report.stderr);
    fs::write(out.join("d11_scorer-resources.txt"), &log)?;
    if !report.status.success() {
        return Err(format!(
            "scorer cubin assembly failed: {}",
            String::from_utf8_lossy(&log)
        )
        .into());
    }
    let image = fs::read(out.join("d11_scorer.cubin"))?;
    if image.len() < 64 || !image.starts_with(b"\x7fELF") {
        return Err("scorer assembly did not emit a nonempty ELF cubin".into());
    }
    fs::write(out.join("cuda-image-target.txt"), image_target)?;
    Ok(())
}
