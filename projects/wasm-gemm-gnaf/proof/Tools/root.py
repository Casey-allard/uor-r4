#!/usr/bin/env python3
"""Regenerate WasmGemmGnaf.lean, and verify no module is stale or unowned.

SPEC 5 fixes the layer structure. A file that belongs to no layer is scratch, and
scratch in the proof path is how a broken or unreviewed module reaches the build.
"""
import os, sys
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
os.chdir(ROOT)
LAYERS = ["Foundation", "Wasm", "Cost", "Gemm", "GNAF", "Universal",
          "Atlas", "Artifact", "Theorems", "Conformance"]
check = "--check" in sys.argv

mods, unowned = {}, []
for r, _, fs in os.walk("WasmGemmGnaf"):
    for f in sorted(fs):
        if not f.endswith(".lean"):
            continue
        rel = os.path.join(r, f)[len("WasmGemmGnaf/"):-len(".lean")]
        parts = rel.split("/")
        if len(parts) < 2 or parts[0] not in LAYERS:
            unowned.append("WasmGemmGnaf/" + rel + ".lean")
            continue
        mods.setdefault(parts[0], []).append("WasmGemmGnaf." + rel.replace("/", "."))

if unowned:
    print("UNOWNED MODULES (belong to no SPEC 5 layer — scratch?):")
    for u in unowned:
        print("  " + u)
    sys.exit(1)

out = ["/-", "  Root module: imports every layer of the WASM-GEMM-GNAF development.",
       "  Generated by `just root`; do not edit by hand.", "-/", ""]
for L in LAYERS:
    if L in mods:
        out.append(f"-- {L}")
        out += ["import " + m for m in sorted(mods[L])]
        out.append("")
text = "\n".join(out).rstrip() + "\n"

if check:
    cur = open("WasmGemmGnaf.lean").read() if os.path.exists("WasmGemmGnaf.lean") else ""
    if cur != text:
        print("WasmGemmGnaf.lean is STALE — run `just root`")
        sys.exit(1)
    print(f"root imports current: {sum(len(v) for v in mods.values())} modules, no unowned files")
else:
    open("WasmGemmGnaf.lean", "w").write(text)
    print(f"root regenerated: {sum(len(v) for v in mods.values())} modules")
