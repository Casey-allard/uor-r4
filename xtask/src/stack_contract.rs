//! Generate and check the human and machine views of stack contracts.

use std::error::Error;
use std::fmt::Write as _;
use std::fs;
use std::io::Error as IoError;
use std::path::{Path, PathBuf};

use repo_model::stack::{self, StackContractFile};

/// Generated human-readable view of every registered stack contract.
pub const MARKDOWN_PATH: &str = "docs/model/STACK-CONTRACT.md";
/// Generated machine-readable view of every registered stack contract.
pub const JSON_PATH: &str = "conformance/generated/stack-contracts.json";

type Fail = Box<dyn Error>;

/// Run `cargo xtask stack-contract`, writing generated files with `--write`
/// and otherwise checking that the committed files are current.
pub fn run(root: &Path, write: bool) -> Result<(), Fail> {
    let source_dir = root.join(stack::DIRECTORY);
    let files = stack::load_dir(&source_dir)?;
    stack::check_all(&files, root)?;

    let markdown = render_markdown(root, &files)?;
    let json = render_json(root, &files)?;
    emit(root, MARKDOWN_PATH, &markdown, write)?;
    emit(root, JSON_PATH, &json, write)?;
    println!(
        "stack-contract: {} contract(s), generated files are {}",
        files.len(),
        if write { "written" } else { "current" }
    );
    Ok(())
}

fn render_markdown(root: &Path, files: &[StackContractFile]) -> Result<String, Fail> {
    let mut out = String::new();
    let w = &mut out;
    writeln!(
        w,
        "<!-- @generated by `cargo xtask stack-contract --write` from {}/*.toml. -->",
        stack::DIRECTORY
    )?;
    writeln!(
        w,
        "<!-- Do not edit. Change the contract source instead. -->"
    )?;
    writeln!(w)?;
    writeln!(w, "# Stack contracts")?;
    writeln!(w)?;
    writeln!(
        w,
        "A stack contract makes one model composition explicit across source, configuration, artifact sections, commands, readings and probes. It is not a capability claim."
    )?;
    writeln!(w)?;
    writeln!(w, "## Evidence status")?;
    writeln!(w)?;
    writeln!(
        w,
        "| Contract | State | Schema | Mechanisms | Evidence | Probes |"
    )?;
    writeln!(w, "| --- | --- | --- | --- | --- | --- |")?;
    for file in files {
        let contract = &file.contract;
        let mechanisms = status_counts(contract.mechanisms.iter().map(|row| row.status.as_str()));
        let evidence = status_counts(contract.evidence.iter().map(|row| row.result.as_str()));
        writeln!(
            w,
            "| `{}` | `{}` | {} | {} | {} | {} |",
            contract.id,
            contract.state.as_str(),
            contract
                .artifact
                .schema
                .as_deref()
                .map_or("--".to_owned(), |schema| format!("`{schema}`")),
            mechanisms,
            evidence,
            contract.probes.len()
        )?;
    }

    for file in files {
        let source = relative(root, &file.path);
        let digest = source_digest(&file.path)?;
        let semantic = semantic_digest(&file.contract)?;
        let contract = &file.contract;
        writeln!(w)?;
        writeln!(w, "## `{}`", contract.id)?;
        writeln!(w)?;
        writeln!(w, "{}", contract.summary)?;
        writeln!(w)?;
        writeln!(w, "- Source: `{source}` (BLAKE3 `{digest}`)")?;
        writeln!(w, "- Semantic hash: `{semantic}`")?;
        writeln!(w, "- Lane: `{}`", contract.lane.as_str())?;
        writeln!(w, "- State: `{}`", contract.state.as_str())?;
        writeln!(w, "- Revision: {}", contract.revision)?;
        writeln!(w, "- Source pin: `{}`", contract.source_pin)?;
        if let Some(decision) = &contract.decision {
            writeln!(w, "- Decision: {}", cell(decision))?;
        }

        writeln!(w)?;
        writeln!(w, "### Model")?;
        writeln!(w)?;
        writeln!(w, "| Field | Value |")?;
        writeln!(w, "| --- | --- |")?;
        writeln!(
            w,
            "| Tokenizer SHA-256 | `{}` |",
            contract.model.tokenizer_sha256
        )?;
        writeln!(w, "| Vocabulary | {} |", contract.model.vocab)?;
        writeln!(w, "| Width | {} |", contract.model.width)?;
        writeln!(w, "| Layers | {} |", contract.model.layers)?;
        writeln!(w, "| Context | {} |", contract.model.context)?;
        writeln!(
            w,
            "| Training context | {} |",
            contract
                .model
                .training_context
                .map_or("--".to_owned(), |context| context.to_string())
        )?;
        writeln!(w, "| Objective | `{}` |", cell(&contract.model.objective))?;
        writeln!(
            w,
            "| Training | {} |",
            contract
                .model
                .training
                .as_deref()
                .map_or("--".to_owned(), cell)
        )?;
        writeln!(
            w,
            "| Serving | {} |",
            contract
                .model
                .serving
                .as_deref()
                .map_or("--".to_owned(), cell)
        )?;

        writeln!(w)?;
        writeln!(w, "### Artifact")?;
        writeln!(w)?;
        writeln!(w, "Family: `{}`", contract.artifact.family)?;
        writeln!(
            w,
            "Schema: {}",
            contract
                .artifact
                .schema
                .as_deref()
                .map_or("--".to_owned(), |schema| format!("`{schema}`"))
        )?;
        writeln!(w)?;
        writeln!(
            w,
            "| Section | Required | Owner | Format | Exponent | Description |"
        )?;
        writeln!(w, "| --- | --- | --- | --- | --- | --- |")?;
        for section in &contract.artifact.sections {
            writeln!(
                w,
                "| `{}` | {} | {} | {} | {} | {} |",
                section.id,
                if section.required { "yes" } else { "no" },
                section
                    .owner
                    .as_deref()
                    .map_or("--".to_owned(), |owner| format!("`{owner}`")),
                section.format.as_deref().map_or("--".to_owned(), cell),
                section
                    .exponent
                    .map_or("--".to_owned(), |exponent| exponent.to_string()),
                cell(&section.description)
            )?;
        }

        writeln!(w)?;
        writeln!(w, "### Inputs")?;
        writeln!(w)?;
        writeln!(w, "| ID | Source | SHA-256 |")?;
        writeln!(w, "| --- | --- | --- |")?;
        for input in &contract.inputs {
            writeln!(
                w,
                "| `{}` | `{}` | `{}` |",
                input.id,
                cell(&input.source),
                input.sha256
            )?;
        }

        writeln!(w)?;
        writeln!(w, "### Mechanisms")?;
        writeln!(w)?;
        writeln!(
            w,
            "| ID | Status | Implementation | Flags | Evidence | Depends on | Conflicts | Sidecars | Load / cleanup | Invariants | Non-claims |"
        )?;
        writeln!(
            w,
            "| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |"
        )?;
        for mechanism in &contract.mechanisms {
            let flags = mechanism
                .flags
                .iter()
                .map(|flag| {
                    format!(
                        "{}={}{}",
                        cell(&flag.name),
                        cell(&flag.value),
                        if flag.required { "" } else { "?" }
                    )
                })
                .collect::<Vec<_>>();
            let lifecycle = format!(
                "{} / {}",
                mechanism
                    .load_order
                    .map_or("--".to_owned(), |order| order.to_string()),
                mechanism
                    .cleanup_order
                    .map_or("--".to_owned(), |order| order.to_string())
            );
            writeln!(
                w,
                "| `{}` | `{}` | `{}` | {} | {} | {} | {} | {} | {} | {} | {} |",
                mechanism.id,
                mechanism.status.as_str(),
                cell(&mechanism.implementation),
                list(&flags),
                list(&mechanism.evidence),
                list(&mechanism.depends_on),
                list(&mechanism.conflicts_with),
                list(&mechanism.sidecars),
                lifecycle,
                list(&mechanism.invariants),
                list(&mechanism.non_claims)
            )?;
        }

        if !contract.evidence.is_empty() {
            writeln!(w)?;
            writeln!(w, "### Evidence")?;
            writeln!(w)?;
            writeln!(
                w,
                "| ID | Kind | Result | Scope | Locator | SHA-256 | Mechanisms | Statement |"
            )?;
            writeln!(w, "| --- | --- | --- | --- | --- | --- | --- | --- |")?;
            for evidence in &contract.evidence {
                writeln!(
                    w,
                    "| `{}` | `{}` | `{}` | {} | `{}` | {} | {} | {} |",
                    evidence.id,
                    evidence.kind.as_str(),
                    evidence.result.as_str(),
                    cell(&evidence.scope),
                    cell(&evidence.locator),
                    evidence
                        .sha256
                        .as_deref()
                        .map_or("--".to_owned(), |sha| format!("`{sha}`")),
                    list(&evidence.mechanisms),
                    cell(&evidence.statement)
                )?;
            }
        }

        writeln!(w)?;
        writeln!(w, "### Readings")?;
        writeln!(w)?;
        writeln!(
            w,
            "| ID | Class | Mechanism | Unit | Better | Bar | Description |"
        )?;
        writeln!(w, "| --- | --- | --- | --- | --- | --- | --- |")?;
        for reading in &contract.readings {
            writeln!(
                w,
                "| `{}` | `{}` | {} | {} | {} | {} | {} |",
                reading.id,
                reading.class.as_str(),
                reading
                    .mechanism
                    .as_deref()
                    .map_or("--".to_owned(), |id| format!("`{id}`")),
                reading.unit.as_deref().map_or("--".to_owned(), cell),
                reading
                    .better
                    .map_or("--".to_owned(), |direction| direction.as_str().to_owned()),
                reading.bar.map_or("--".to_owned(), |bar| bar.to_string()),
                cell(&reading.description)
            )?;
        }

        writeln!(w)?;
        writeln!(w, "### Probes")?;
        writeln!(w)?;
        writeln!(
            w,
            "| ID | Class | Mechanism | Fixture | Layers | Axis | Expectation | Cases |"
        )?;
        writeln!(w, "| --- | --- | --- | --- | --- | --- | --- | --- |")?;
        for probe in &contract.probes {
            writeln!(
                w,
                "| `{}` | `{}` | `{}` | {} | {} | {} | {} | {} |",
                probe.id,
                probe.class.as_str(),
                probe.mechanism,
                probe
                    .fixture
                    .as_deref()
                    .map_or("--".to_owned(), |fixture| format!("`{fixture}`")),
                probe
                    .layers
                    .iter()
                    .map(|layer| layer.as_str())
                    .collect::<Vec<_>>()
                    .join(", "),
                cell(&probe.axis),
                cell(&probe.expectation),
                list(&probe.cases)
            )?;
        }

        writeln!(w)?;
        writeln!(w, "### Commands")?;
        writeln!(w)?;
        for command in &contract.commands {
            writeln!(
                w,
                "- **{} (`{}`)**: `{} {}`",
                command.id,
                command.role.as_str(),
                command.program,
                shell_words(&command.args)
            )?;
            if !command.env.is_empty() || !command.inputs.is_empty() || !command.outputs.is_empty()
            {
                writeln!(
                    w,
                    "  - env {}; inputs {}; outputs {}; timeout {}",
                    list(&command.env),
                    list(&command.inputs),
                    list(&command.outputs),
                    command
                        .timeout_seconds
                        .map_or("--".to_owned(), |seconds| format!("{seconds}s"))
                )?;
            }
        }

        writeln!(w)?;
        writeln!(w, "### Non-claims")?;
        writeln!(w)?;
        for non_claim in &contract.non_claims {
            writeln!(w, "- **`{}`**: {}", non_claim.id, non_claim.statement)?;
        }
    }
    Ok(out)
}

fn render_json(root: &Path, files: &[StackContractFile]) -> Result<String, Fail> {
    let mut contracts = Vec::with_capacity(files.len());
    for file in files {
        contracts.push(serde_json::json!({
            "source": relative(root, &file.path),
            "source_blake3": source_digest(&file.path)?,
            "semantic_blake3": semantic_digest(&file.contract)?,
            "contract": &file.contract,
        }));
    }
    let document = serde_json::json!({
        "schema": "uor-r4.stack-contract.generated/2",
        "source_directory": stack::DIRECTORY,
        "contracts": contracts,
    });
    Ok(serde_json::to_string_pretty(&document)? + "\n")
}

fn source_digest(path: &Path) -> Result<String, Fail> {
    let bytes = fs::read(path)?;
    Ok(blake3::hash(&bytes).to_hex().to_string())
}

fn semantic_digest(contract: &repo_model::stack::StackContract) -> Result<String, Fail> {
    Ok(blake3::hash(&serde_json::to_vec(contract)?)
        .to_hex()
        .to_string())
}

fn emit(root: &Path, relative_path: &str, contents: &str, write: bool) -> Result<(), Fail> {
    let path: PathBuf = root.join(relative_path);
    if write {
        if let Some(parent) = path.parent() {
            fs::create_dir_all(parent)?;
        }
        fs::write(&path, contents)?;
        return Ok(());
    }
    let committed = fs::read_to_string(&path).map_err(|error| {
        IoError::other(format!(
            "{}: {error}\nrun `cargo xtask stack-contract --write`",
            path.display()
        ))
    })?;
    if committed != contents {
        return Err(IoError::other(format!(
            "{} is stale: it disagrees with {}. Run `cargo xtask stack-contract --write`.",
            path.display(),
            stack::DIRECTORY
        ))
        .into());
    }
    Ok(())
}

fn relative(root: &Path, path: &Path) -> String {
    path.strip_prefix(root)
        .unwrap_or(path)
        .to_string_lossy()
        .replace('\\', "/")
}

fn cell(text: &str) -> String {
    text.replace('|', "\\|").replace('\n', " ")
}

fn list(values: &[String]) -> String {
    if values.is_empty() {
        "--".to_owned()
    } else {
        values
            .iter()
            .map(|value| format!("`{}`", cell(value)))
            .collect::<Vec<_>>()
            .join("<br>")
    }
}

fn status_counts<'a>(values: impl Iterator<Item = &'a str>) -> String {
    let mut counts = std::collections::BTreeMap::new();
    for value in values {
        *counts.entry(value).or_insert(0usize) += 1;
    }
    if counts.is_empty() {
        return "--".to_owned();
    }
    counts
        .into_iter()
        .map(|(status, count)| format!("`{status}` {count}"))
        .collect::<Vec<_>>()
        .join("<br>")
}

fn shell_words(values: &[String]) -> String {
    values
        .iter()
        .map(|value| {
            if value
                .bytes()
                .all(|byte| byte.is_ascii_alphanumeric() || b"-_.:/=+".contains(&byte))
            {
                value.clone()
            } else {
                format!("'{}'", value.replace('\'', "'\\''"))
            }
        })
        .collect::<Vec<_>>()
        .join(" ")
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn checked_in_contracts_render_deterministically() {
        let root = repo_model::repo_root();
        let files = stack::load_dir(&root.join(stack::DIRECTORY)).expect("contracts load");
        stack::check_all(&files, &root).expect("contracts check");

        let markdown = render_markdown(&root, &files).expect("markdown renders");
        assert_eq!(
            markdown,
            render_markdown(&root, &files).expect("markdown renders twice")
        );
        assert_eq!(
            fs::read_to_string(root.join(MARKDOWN_PATH)).expect("committed markdown"),
            markdown
        );
        assert!(markdown.contains("<!-- @generated"));
        assert!(markdown.contains("### Mechanisms"));
        assert!(markdown.contains("### Probes"));

        let json = render_json(&root, &files).expect("json renders");
        assert_eq!(
            json,
            render_json(&root, &files).expect("json renders twice")
        );
        assert_eq!(
            fs::read_to_string(root.join(JSON_PATH)).expect("committed json"),
            json
        );
        assert!(json.contains("\"schema\": \"uor-r4.stack-contract.generated/2\""));
        assert!(json.contains("\"source_blake3\""));
        assert!(json.contains("\"semantic_blake3\""));
        assert!(markdown.contains("## Evidence status"));
    }

    #[test]
    fn command_rendering_quotes_only_when_needed() {
        assert_eq!(
            shell_words(&["--context".to_owned(), "192".to_owned()]),
            "--context 192"
        );
        assert_eq!(
            shell_words(&["label with spaces".to_owned()]),
            "'label with spaces'"
        );
    }
}
