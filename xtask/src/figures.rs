//! `cargo xtask figures [--write]`: the project's status diagrams, generated.
//!
//! The README and `docs/geometry.md` diagrams are drawn here, in Rust (D27: Rust
//! for tooling), so a status change is a one-line edit and a reviewable diff
//! instead of a hand-edited SVG. Every figure uses one vocabulary: cards with a
//! status, status pills, arrows and a legend, in the colour-blind-safe palette the
//! earlier figures used. Text never overflows its card: each line's width is
//! estimated and the task fails instead of writing a clipped figure.
//!
//! Without `--write` the task checks that every generated file is current (the
//! figures are deterministic), so CI can catch a hand edit or a stale status.
//! The mathematical illustrations under `docs/figures/geometry/` that this file
//! does not name (the 600-cell, the Hopf map, the zeta phases and so on) are
//! outside it: they are unchanged mathematics, generated by their own script.

use std::fmt::Write as _;
use std::path::Path;

type Fail = Box<dyn std::error::Error>;
/// A text style: size, weight and fill.
type Font<'a> = (f64, u16, &'a str);
/// A box style: fill, stroke, stroke width and optional dash.
type Paint<'a> = (&'a str, &'a str, f64, Option<&'a str>);

const FONT: &str = "-apple-system, BlinkMacSystemFont, 'Segoe UI', Helvetica, Arial, sans-serif";
const INK: &str = "#1F2328";
const BODY: &str = "#2B3138";
const MUTED: &str = "#57606A";
const ARROW: &str = "#424A53";
const BLUE: &str = "#0072B2";
const GREEN: &str = "#007A5E";
const ORANGE: &str = "#E69F00";
const VERM: &str = "#D55E00";
const PURPLE: &str = "#7A4FA3";
const PANEL: &str = "#F6F8FA";
const RULE: &str = "#D0D7DE";
const DATE: &str = "13 October 2026";

/// Where a piece of the project stands. "Built" means source built and tested,
/// not trained; "Held" means it waits on an owner hold.
#[derive(Clone, Copy, PartialEq)]
enum St {
    Working,
    Built,
    Progress,
    Planned,
    Held,
    Paused,
    Frozen,
}

impl St {
    fn label(self) -> &'static str {
        match self {
            St::Working => "WORKING",
            St::Built => "BUILT & TESTED",
            St::Progress => "IN PROGRESS",
            St::Planned => "PLANNED",
            St::Held => "HELD",
            St::Paused => "PAUSED",
            St::Frozen => "FROZEN",
        }
    }
    fn legend(self) -> &'static str {
        match self {
            St::Working => "Working",
            St::Built => "Built & tested",
            St::Progress => "In progress",
            St::Planned => "Planned",
            St::Held => "Held by the owner",
            St::Paused => "Paused",
            St::Frozen => "Frozen",
        }
    }
    /// (fill, stroke, stroke width, dash)
    fn card(self) -> (&'static str, &'static str, f64, Option<&'static str>) {
        match self {
            St::Working => ("#E3F4EE", GREEN, 2.5, None),
            St::Built => ("#E4EFF8", BLUE, 1.75, None),
            St::Progress => ("url(#hP)", "#B87A00", 2.0, None),
            St::Planned => ("#FFFFFF", "#6E7781", 1.75, Some("6 5")),
            St::Held => ("#F4F0F8", PURPLE, 2.0, Some("9 4")),
            St::Paused => ("#F6F8FA", "#8C959F", 1.75, Some("2 4")),
            St::Frozen => ("url(#hF)", "#8C959F", 1.5, Some("2 3")),
        }
    }
    /// (fill, stroke, text, dash)
    fn pill(
        self,
    ) -> (
        &'static str,
        &'static str,
        &'static str,
        Option<&'static str>,
    ) {
        match self {
            St::Working => (GREEN, GREEN, "#FFFFFF", None),
            St::Built => (BLUE, BLUE, "#FFFFFF", None),
            St::Progress => (ORANGE, "#B87A00", INK, None),
            St::Planned => ("#FFFFFF", "#6E7781", ARROW, Some("4 3")),
            St::Held => (PURPLE, PURPLE, "#FFFFFF", None),
            St::Paused => ("#8C959F", "#8C959F", "#FFFFFF", None),
            St::Frozen => ("#57606A", "#57606A", "#FFFFFF", None),
        }
    }
}

fn esc(s: &str) -> String {
    s.replace('&', "&amp;")
        .replace('<', "&lt;")
        .replace('>', "&gt;")
}

/// Rough rendered width of `s` at `size` px in the figures' sans-serif face.
fn text_width(s: &str, size: f64, bold: bool) -> f64 {
    let per = if bold { 0.6 } else { 0.55 };
    s.chars().count() as f64 * size * per
}

struct Svg {
    name: String,
    w: f64,
    h: f64,
    body: String,
    overflow: Vec<String>,
}

impl Svg {
    fn new(name: &str, w: f64, h: f64) -> Svg {
        Svg {
            name: name.to_string(),
            w,
            h,
            body: String::new(),
            overflow: Vec::new(),
        }
    }

    fn text(&mut self, [x, y]: [f64; 2], (size, weight, fill): Font, anchor: &str, s: &str) {
        let _ = writeln!(
            self.body,
            r#"<text x="{x}" y="{y}" font-size="{size}" font-weight="{weight}" fill="{fill}" text-anchor="{anchor}">{}</text>"#,
            esc(s)
        );
    }

    /// Text that must fit in `room` px; an overflow is recorded and fails the task.
    fn fit(&mut self, at: [f64; 2], (size, weight, fill): Font, room: f64, s: &str) {
        let need = text_width(s, size, weight >= 600);
        if need > room {
            self.overflow.push(format!(
                "{}: \"{s}\" needs ~{need:.0}px, has {room:.0}px",
                self.name
            ));
        }
        self.text(at, (size, weight, fill), "start", s);
    }

    fn rect(&mut self, [x, y, w, h]: [f64; 4], rx: f64, (fill, stroke, sw, dash): Paint) {
        let d = dash
            .map(|d| format!(r#" stroke-dasharray="{d}""#))
            .unwrap_or_default();
        let _ = writeln!(
            self.body,
            r#"<rect x="{x}" y="{y}" width="{w}" height="{h}" rx="{rx}" fill="{fill}" stroke="{stroke}" stroke-width="{sw}"{d}/>"#
        );
    }

    fn pill(&mut self, x: f64, y: f64, st: St) {
        let label = st.label();
        let w = (label.chars().count() as f64 * 7.0 + 20.0).round();
        let (fill, stroke, ink, dash) = st.pill();
        self.rect([x, y, w, 22.0], 11.0, (fill, stroke, 1.5, dash));
        let _ = writeln!(
            self.body,
            r#"<text x="{}" y="{}" font-size="11" font-weight="700" fill="{ink}" text-anchor="middle" letter-spacing="0.4">{}</text>"#,
            x + w / 2.0,
            y + 15.0,
            esc(label)
        );
    }

    /// A card: title, body lines and (optionally) its status pill at the bottom.
    fn card(&mut self, [x, y, w, h]: [f64; 4], st: St, title: &str, lines: &[&str], pill: bool) {
        let (fill, stroke, sw, dash) = st.card();
        self.rect([x, y, w, h], 10.0, (fill, stroke, sw, dash));
        let room = w - 28.0;
        self.fit([x + 14.0, y + 26.0], (15.0, 700, INK), room, title);
        for (i, l) in lines.iter().enumerate() {
            self.fit(
                [x + 14.0, y + 47.0 + 16.0 * i as f64],
                (12.5, 400, BODY),
                room,
                l,
            );
        }
        let bottom = y + 47.0 + 16.0 * lines.len() as f64;
        if pill {
            if bottom > y + h - 30.0 {
                self.overflow.push(format!(
                    "{}: card \"{title}\" body runs into its pill",
                    self.name
                ));
            }
            self.pill(x + 14.0, y + h - 30.0, st);
        } else if bottom - 12.0 > y + h {
            self.overflow.push(format!(
                "{}: card \"{title}\" body runs past its bottom",
                self.name
            ));
        }
    }

    fn path(&mut self, d: &str, stroke: &str, sw: f64, dash: Option<&str>, arrow: bool) {
        let ds = dash
            .map(|d| format!(r#" stroke-dasharray="{d}""#))
            .unwrap_or_default();
        let m = if arrow {
            r#" marker-end="url(#ah)""#
        } else {
            ""
        };
        let _ = writeln!(
            self.body,
            r#"<path d="{d}" fill="none" stroke="{stroke}" stroke-width="{sw}"{ds}{m}/>"#
        );
    }

    fn arrow(&mut self, x1: f64, y1: f64, x2: f64, y2: f64, dash: bool) {
        self.path(
            &format!("M{x1},{y1} L{x2},{y2}"),
            ARROW,
            2.0,
            if dash { Some("7 5") } else { None },
            true,
        );
    }

    fn circle(&mut self, cx: f64, cy: f64, r: f64, fill: &str, stroke: &str, sw: f64) {
        let _ = writeln!(
            self.body,
            r#"<circle cx="{cx}" cy="{cy}" r="{r}" fill="{fill}" stroke="{stroke}" stroke-width="{sw}"/>"#
        );
    }

    fn header(&mut self, title: &str, sub: &str) {
        self.rect(
            [0.5, 0.5, self.w - 1.0, self.h - 1.0],
            16.0,
            ("#FFFFFF", RULE, 1.0, None),
        );
        let room = self.w - 80.0;
        self.fit([40.0, 52.0], (26.0, 700, INK), room, title);
        self.fit([40.0, 80.0], (14.5, 400, MUTED), room, sub);
    }

    fn section(&mut self, y: f64, s: &str) {
        self.text([40.0, y], (14.0, 700, BLUE), "start", s);
    }

    fn legend(&mut self, y: f64, items: &[St]) {
        self.path(
            &format!("M40,{} L{},{}", y - 22.0, self.w - 40.0, y - 22.0),
            RULE,
            1.0,
            None,
            false,
        );
        self.text([40.0, y], (13.5, 700, INK), "start", "Status");
        let mut x = 110.0;
        for st in items {
            let (fill, stroke, sw, dash) = st.card();
            self.rect(
                [x, y - 15.0, 34.0, 20.0],
                5.0,
                (fill, stroke, sw.min(2.0), dash),
            );
            self.text([x + 42.0, y], (13.0, 400, BODY), "start", st.legend());
            x += 42.0 + text_width(st.legend(), 13.0, false) + 30.0;
        }
        if x > self.w - 20.0 {
            self.overflow
                .push(format!("{}: legend runs past the right edge", self.name));
        }
    }

    fn finish(self, title: &str, desc: &str) -> Result<String, Fail> {
        if !self.overflow.is_empty() {
            return Err(format!("text does not fit:\n  {}", self.overflow.join("\n  ")).into());
        }
        let mut out = String::new();
        let _ = writeln!(out, r#"<?xml version="1.0" encoding="UTF-8"?>"#);
        let _ = writeln!(
            out,
            r#"<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {w} {h}" width="{w}" height="{h}" role="img" aria-labelledby="t d" font-family="{FONT}">"#,
            w = self.w,
            h = self.h
        );
        let _ = writeln!(out, r#"<title id="t">{}</title>"#, esc(title));
        let _ = writeln!(out, r#"<desc id="d">{}</desc>"#, esc(desc));
        out.push_str(concat!(
            r##"<defs><marker id="ah" viewBox="0 0 10 10" refX="9" refY="5" markerWidth="8" markerHeight="8" orient="auto-start-reverse"><path d="M0,0 L10,5 L0,10 z" fill="#424A53"/></marker>"##,
            r##"<pattern id="hP" width="9" height="9" patternUnits="userSpaceOnUse" patternTransform="rotate(45)"><rect width="9" height="9" fill="#FFF7E3"/><line x1="0" y1="0" x2="0" y2="9" stroke="#F1D79A" stroke-width="2.2"/></pattern>"##,
            r##"<pattern id="hF" width="8" height="8" patternUnits="userSpaceOnUse"><rect width="8" height="8" fill="#F0F2F4"/><path d="M0,0 L8,8 M8,0 L0,8" stroke="#D3D8DD" stroke-width="1"/></pattern></defs>"##,
            "\n"
        ));
        out.push_str(&self.body);
        out.push_str("</svg>\n");
        Ok(out)
    }
}

