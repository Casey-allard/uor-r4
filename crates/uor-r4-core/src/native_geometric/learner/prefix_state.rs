//! One learned older-prefix group-state / read channel above the frozen local prior.
//!
//! # What this is
//!
//! The frozen step-512 prior predicts `x[i+1]` from the local pair `(x[i-1], x[i])` only. This
//! component adds **one exact `2I` group register** summarising the *older* part of the same
//! bounded context, excluding that pair:
//!
//! ```text
//! q_i = product over j in [max(0, i-63), i-1)  of  gamma[ argmax A[x[j], :] ]
//! ```
//!
//! (`[start, end)` is Rust half-open.) An empty older prefix contributes **zero** residual. The
//! learned token-to-palette choice `A` has 8 offline floating logits per token; only the hard
//! argmax (lowest palette ID on ties) is exported, nibble-packed. The palette is a fixed,
//! data-independent set of 8 exact group elements containing identity and two noncommuting
//! generators, so its closure is the full 120-element group.
//!
//! # Served forward (hard, integer, multiplier-free)
//!
//! ```text
//! Z_total[v] = Z_parent[v] + ((sum_j Wcode[v,j] * Rcode[q,j]) << 8)
//! ```
//!
//! implemented as: read `h[j] = Rcode[q,j] << 5` and apply the ternary `Wcode` with output shift 3
//! (because `5 + 3 = 8`). The parent's `F = 10` remains the sole score-to-logit exponent, so each
//! residual code-sum unit is `2^8 * 2^-10 = 0.25` logit. Both maps are fixed-scale ternary tables
//! built with `TernaryLinear::from_packed` (no adaptive quantizer), so training, export/reload and
//! generation execute the identical integer forward.
//!
//! # Scope
//!
//! This register is a **bounded coalescing summary**, not exact memory, a semantic metric, or an
//! independent golden/Galois companion. Pure group transitions are bijections and cannot
//! selectively overwrite; the 64-token context supplies explicit bounded forgetting. No zeta
//! feature, gate, bias, normalizer or sampler is added.
#![forbid(unsafe_code)]

use std::collections::HashMap;
use std::sync::OnceLock;

use super::group_table::{group_table, GROUP_ORDER, ROW_STRIDE};
use super::lowbit::TernaryLinear;
use super::prior_learning::{PriorCore, BIAS_CODE_MAX, PRIOR_CLAMP};

/// Number of palette actions.
pub const PALETTE_SIZE: usize = 8;
/// Reader hidden width.
pub const READER_WIDTH: usize = 16;
/// Reader row shift: `h[j] = Rcode[q,j] << READER_SHIFT`.
pub const READER_SHIFT: u32 = 5;
/// Ternary output row shift; `READER_SHIFT + OUTPUT_SHIFT = 8` is the declared residual shift.
pub const OUTPUT_SHIFT: u32 = 3;
/// Declared residual score shift.
pub const RESIDUAL_SHIFT: u32 = READER_SHIFT + OUTPUT_SHIFT;
/// Max older-prefix tokens: `H = 64` context minus the two local tokens.
pub const MAX_OLDER_TOKENS: usize = 62;
/// Largest absolute residual score: 16 ternary reader units times `2^8`.
pub const RESIDUAL_MAX_ABS: i64 = (READER_WIDTH as i64) << RESIDUAL_SHIFT;

/// Reader/output Adam learning rate.
pub const READER_LR: f32 = 0.03;
/// Action-logit Adam learning rate.
pub const ACTION_LR: f32 = 0.003;
/// Adam betas, as one fixed pilot configuration.
pub const BETA1: f32 = 0.9;
pub const BETA2: f32 = 0.999;
pub const ADAM_EPS: f32 = 1e-8;
/// Ternary threshold; `|v| >= 0.5` maps to `±1` (ties resolve to magnitude one).
pub const TERNA_TIE: f32 = 0.5;

const CODE_ZERO: u8 = 0;
const CODE_POS: u8 = 1;
const CODE_NEG: u8 = 2;

// ---------------------------------------------------------------------------
// Palette
// ---------------------------------------------------------------------------

/// A fixed, data-independent set of exact group elements. Contains the identity and a chosen
/// noncommuting generator pair, so the subgroup generated by the palette is the whole group.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct Palette {
    pub elements: [u8; PALETTE_SIZE],
    pub identity: u8,
}

impl Palette {
    /// Every distinct element reachable from the palette under composition, by BFS closure.
    pub fn closure_size(&self) -> usize {
        let t = group_table();
        let mut seen = vec![false; GROUP_ORDER];
        let mut queue = vec![t.identity as usize];
        seen[t.identity as usize] = true;
        // Seed with the palette itself.
        for &e in self.elements.iter() {
            if !seen[e as usize] {
                seen[e as usize] = true;
                queue.push(e as usize);
            }
        }
        while let Some(a) = queue.pop() {
            for &e in self.elements.iter() {
                let p = t.product[a * ROW_STRIDE + e as usize] as usize;
                if !seen[p] {
                    seen[p] = true;
                    queue.push(p);
                }
            }
        }
        seen.iter().filter(|s| **s).count()
    }
}

/// The order of the subgroup generated by `gens`.
fn generated_order(gens: &[u8]) -> usize {
    let t = group_table();
    let mut seen = vec![false; GROUP_ORDER];
    let mut queue = vec![t.identity as usize];
    seen[t.identity as usize] = true;
    for &g in gens {
        if !seen[g as usize] {
            seen[g as usize] = true;
            queue.push(g as usize);
        }
    }
    while let Some(a) = queue.pop() {
        for &g in gens {
            let p = t.product[a * ROW_STRIDE + g as usize] as usize;
            if !seen[p] {
                seen[p] = true;
                queue.push(p);
            }
        }
    }
    seen.iter().filter(|s| **s).count()
}

/// Deterministically choose the first canonical noncommuting generator pair that generates the
/// whole group, then take the identity, `a`, `b`, their inverses, `a*b`, `b*a` and the smallest
/// remaining element as the eight palette entries. No target data is consulted.
pub fn build_palette() -> Result<Palette, String> {
    let t = group_table();
    let e = t.identity;
    for a in 0..GROUP_ORDER as u8 {
        if a == e {
            continue;
        }
        for b in 0..GROUP_ORDER as u8 {
            if b == e || b == a {
                continue;
            }
            let ab = t.product[a as usize * ROW_STRIDE + b as usize];
            let ba = t.product[b as usize * ROW_STRIDE + a as usize];
            if ab == ba {
                continue;
            }
            if generated_order(&[a, b]) != GROUP_ORDER {
                continue;
            }
            let mut els: Vec<u8> = vec![
                e,
                a,
                b,
                t.inverse[a as usize],
                t.inverse[b as usize],
                ab,
                ba,
            ];
            for cand in 0..GROUP_ORDER as u8 {
                if els.len() == PALETTE_SIZE {
                    break;
                }
                if !els.contains(&cand) {
                    els.push(cand);
                }
            }
            if els.len() != PALETTE_SIZE {
                return Err("palette could not be filled to eight distinct elements".into());
            }
            let mut elements = [0u8; PALETTE_SIZE];
            elements.copy_from_slice(&els);
            let p = Palette {
                elements,
                identity: e,
            };
            if p.closure_size() != GROUP_ORDER {
                return Err("palette closure is not the full group".into());
            }
            return Ok(p);
        }
    }
    Err("no noncommuting generator pair with full closure was found".into())
}

static PALETTE: OnceLock<Palette> = OnceLock::new();

/// The process-wide palette, built on first use.
///
/// # Panics
/// Panics only if the exact group table itself is broken (no noncommuting generator pair), which the
/// `group_table` fixtures already exclude.
pub fn palette() -> &'static Palette {
    PALETTE.get_or_init(|| build_palette().expect("exact 2I palette"))
}

