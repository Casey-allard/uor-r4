    /// The reader/output adjoints are checked against literal small integer values, and the
    /// palette/state adjoints against a finite difference of the continuous multilinear extension
    /// plus softmax Jacobian. Hard argmax is deliberately NOT finite-differenced.
    #[test]
    fn state_adjoint_matches_finite_difference_of_the_continuous_extension() {
        let p = palette();
        let t = group_table();
        let n = GROUP_ORDER;

        // c[h] = sum_{s,k: s*gamma[k]=h} c_prev[s] * pi[k]
        let convolve = |c_prev: &[f64], pi: &[f64; PALETTE_SIZE]| -> Vec<f64> {
            let mut c = vec![0.0f64; n];
            for s in 0..n {
                if c_prev[s] == 0.0 {
                    continue;
                }
                for k in 0..PALETTE_SIZE {
                    let h = t.product[s * ROW_STRIDE + p.elements[k] as usize] as usize;
                    c[h] += c_prev[s] * pi[k];
                }
            }
            c
        };

        // A fixed one-hot chain of length 2 and a nonuniform read weight over states.
        let q0 = 3usize;
        let k0 = 1usize;
        let k1 = 5usize;
        let mut c1 = vec![0.0f64; n];
        {
            let mut c0 = vec![0.0f64; n];
            c0[q0] = 1.0;
            let mut pi0 = [0.0f64; PALETTE_SIZE];
            pi0[k0] = 1.0;
            c1 = convolve(&c0, &pi0);
        }
        let mut pi1 = [0.0f64; PALETTE_SIZE];
        pi1[k1] = 1.0;
        let c2 = convolve(&c1, &pi1);

        // Read weight: u_h = sum_j g_j * Rcode[h,j] for a fixed literal g.
        let g: Vec<f64> = (0..READER_WIDTH).map(|j| (j as f64) - 6.5).collect();
        let rcode = |h: usize, j: usize| -> f64 {
            // A deterministic ternary reader, independent of the trainer.
            (((h * 7 + j * 13) % 3) as i64 - 1) as f64
        };
        let loss = |c: &[f64]| -> f64 {
            let mut l = 0.0;
            for h in 0..n {
                let mut u = 0.0;
                for j in 0..READER_WIDTH {
                    u += g[j] * rcode(h, j);
                }
                l += u * c[h];
            }
            l
        };

        // Analytic state adjoint at c2: u[h] = sum_j g_j Rcode[h,j].
        let mut u = vec![0.0f64; n];
        for h in 0..n {
            for j in 0..READER_WIDTH {
                u[h] += g[j] * rcode(h, j);
            }
        }
        // d_prev[s] = u[s * gamma[k1]]; d_palette[k] = u[c1_state * gamma[k]].
        let c1_state = t.product[q0 * ROW_STRIDE + p.elements[k0] as usize] as usize;
        let mut u_prev = vec![0.0f64; n];
        for s in 0..n {
            u_prev[s] = u[t.product[s * ROW_STRIDE + p.elements[k1] as usize] as usize];
        }
        let eps = 1e-6;
        // Two-step finite differences: pi1 first, then pi0.
        let mut c0 = vec![0.0f64; n];
        c0[q0] = 1.0;
        let pi0 = {
            let mut p0 = [0.0f64; PALETTE_SIZE];
            p0[k0] = 1.0;
            p0
        };
        for k in 0..PALETTE_SIZE {
            let mut pp = pi1;
            pp[k] += eps;
            let mut pm = pi1;
            pm[k] -= eps;
            let l_plus = loss(&convolve(&c1, &pp));
            let l_minus = loss(&convolve(&c1, &pm));
            let fd = (l_plus - l_minus) / (2.0 * eps);
            let analytic = u[t.product[c1_state * ROW_STRIDE + p.elements[k] as usize] as usize];
            assert!(
                (fd - analytic).abs() < 1e-6,
                "step-1 palette {k}: fd {fd} vs analytic {analytic}"
            );
        }
        for k in 0..PALETTE_SIZE {
            let mut pp = pi0;
            pp[k] += eps;
            let mut pm = pi0;
            pm[k] -= eps;
            let l_plus = loss(&convolve(&convolve(&c0, &pp), &pi1));
            let l_minus = loss(&convolve(&convolve(&c0, &pm), &pi1));
            let fd = (l_plus - l_minus) / (2.0 * eps);
            let analytic = u_prev[t.product[q0 * ROW_STRIDE + p.elements[k] as usize] as usize];
            assert!(
                (fd - analytic).abs() < 1e-6,
                "step-0 palette {k}: fd {fd} vs analytic {analytic}"
            );
        }
        let _ = c2;
    }

    #[test]
    fn learned_older_gradient_reaches_an_earlier_token_while_local_inputs_are_unchanged() {
        // One window; the only older token for i=2 is x[0]. Only that token's action can carry
        // older-prefix information into the i=2 prediction, and the local pair is untouched.
        let mut tr = trainer(Arm::LearnedOlder, 13);
        let windows = vec![vec![4u32, 5, 6, 7, 8, 9, 10, 11]];
        let mut cache = ParentCache::default();
        for _ in 0..24 {
            tr.train_batch(&windows, &mut cache, false)
                .expect("warm-up");
            let core = tr.hard_core().unwrap();
            if (0..64).any(|r| (0..READER_WIDTH).any(|j| core.wg.weight(r, j) != 0)) {
                break;
            }
        }
        let before = tr.a_logits.clone();
        tr.train_batch(&windows, &mut cache, true).expect("batch");
        assert_ne!(
            tr.a_logits, before,
            "older-token action credit must move actions"
        );
        // The local pair is not part of the older prefix at the earliest positions; the mask is explicit.
        assert_eq!(PrefixCore::older_len(0), 0);
        assert_eq!(PrefixCore::older_len(1), 0);
        assert_eq!(PrefixCore::older_len(2), 1);
        // Floating action-logit movement is NOT a hard transition: one update at lr 0.003 rarely
        // flips an argmax. Hard action changes/occupancy are measured across the real fit instead.
        let transitions = tr
            .hard_actions()
            .iter()
            .zip(tr.initial_actions().iter())
            .filter(|(a, b)| a != b)
            .count();
        assert!(
            transitions < 64,
            "a single update cannot rewrite every action"
        );
    }

    #[test]
    fn checkpoint_round_trips_and_resume_matches_an_uninterrupted_run() {
        let windows = vec![
            vec![1u32, 2, 3, 4, 5, 6, 7, 8],
            vec![9u32, 10, 11, 12, 13, 14, 15, 16],
            vec![17u32, 18, 19, 20, 21, 22, 23, 24],
            vec![25u32, 26, 27, 28, 29, 30, 31, 32],
        ];
        let mut a = trainer(Arm::LearnedOlder, 13);
        let mut cache = ParentCache::default();
        for _ in 0..3 {
            a.train_batch(&windows, &mut cache, true).unwrap();
        }
        let bytes = a.checkpoint_bytes();

        let mut b = trainer(Arm::LearnedOlder, 13);
        b.resume_from(&bytes).expect("resume");
        assert_eq!(b.reader_updates, a.reader_updates);
        assert_eq!(b.action_updates, a.action_updates);
        assert_eq!(b.r_master, a.r_master);
        assert_eq!(b.w_master, a.w_master);
        assert_eq!(b.a_logits, a.a_logits);

        // A resumed run continues exactly.
        let mut a2 = trainer(Arm::LearnedOlder, 13);
        a2.resume_from(&bytes).unwrap();
        let l1 = a2.train_batch(&windows, &mut cache, true).unwrap();
        let l2 = a.train_batch(&windows, &mut cache, true).unwrap();
        assert_eq!(l1, l2);
        assert_eq!(a2.a_logits, a.a_logits);
        assert_eq!(a2.r_master, a.r_master);

        // Wrong parent identity is rejected.
        let mut c = PrefixTrainer::new(
            tiny_parent(64, 32),
            palette().clone(),
            Arm::LearnedOlder,
            13,
            8,
            2,
            4,
            2,
            [9u8; 32],
        )
        .unwrap();
        assert!(c.resume_from(&bytes).is_err());
    }

    #[test]
    fn action_credit_is_zero_before_warmup_and_nonzero_after() {
        let windows = vec![vec![1u32, 2, 3, 4, 5, 6, 7, 8]];
        let mut tr = trainer(Arm::LearnedOlder, 13);
        let mut cache = ParentCache::default();
        let before = tr.a_logits.clone();
        tr.train_batch(&windows, &mut cache, false).unwrap();
        assert_eq!(tr.a_logits, before, "warm-up must not move action logits");
        assert_eq!(tr.action_updates, 0);
        assert_eq!(tr.reader_updates, 1);
        // Action credit is exactly zero until the output masters ternarize away from zero, because a
        // zero output row gives `g = 0` and therefore a zero state adjoint. This is the declared
        // warm-up, and it is why the schedule gives the reader 64 updates first.
        let mut escaped = false;
        for _ in 0..24 {
            tr.train_batch(&windows, &mut cache, false).unwrap();
            let core = tr.hard_core().unwrap();
            if (0..64).any(|r| (0..READER_WIDTH).any(|j| core.wg.weight(r, j) != 0)) {
                escaped = true;
                break;
            }
        }
        assert!(escaped, "output masters must escape the zero ternary class");
        assert_eq!(tr.action_updates, 0);
        assert_eq!(tr.a_logits, before);
        tr.train_batch(&windows, &mut cache, true).unwrap();
        assert_ne!(tr.a_logits, before, "post-warm-up must learn actions");
        assert_eq!(tr.action_updates, 1);
    }

