/// Ternarize a row-major master with the declared `|v| >= 0.5` rule and pack two bits per weight.
pub fn pack_fixed(master: &[f32], rows: usize, cols: usize, shift: u32) -> (Vec<u8>, Vec<u32>) {
    assert_eq!(master.len(), rows * cols);
    let mut packed = vec![0u8; (rows * cols).div_ceil(4)];
    for (i, &v) in master.iter().enumerate() {
        let code = if v >= TERNA_TIE {
            CODE_POS
        } else if v <= -TERNA_TIE {
            CODE_NEG
        } else {
            CODE_ZERO
        };
        if code != CODE_ZERO {
            let byte = i >> 2;
            let slot = (i & 3) as u32;
            packed[byte] |= code << (slot * 2);
        }
    }
    (packed, vec![shift; rows])
}

/// The served hard form of the channel: frozen parent plus the fixed-scale residual read.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct PrefixCore {
    pub parent: PriorCore,
    /// `GROUP_ORDER x READER_WIDTH`, uniform `READER_SHIFT`.
    pub reader: TernaryLinear,
    /// `vocab x READER_WIDTH`, uniform `OUTPUT_SHIFT`.
    pub wg: TernaryLinear,
    /// Hard per-token palette IDs.
    pub action_codes: Vec<u8>,
    pub palette: Palette,
    /// Arm identity, for report labelling only; it never changes the served computation.
    pub arm: u8,
}

impl PrefixCore {
    /// Fixed-scale constructor from hard codes. Validates shapes and the combined envelope.
    pub fn from_parts(
        parent: PriorCore,
        reader: TernaryLinear,
        wg: TernaryLinear,
        action_codes: Vec<u8>,
        palette: Palette,
        arm: u8,
    ) -> Result<Self, String> {
        if reader.rows != GROUP_ORDER || reader.cols != READER_WIDTH {
            return Err(format!(
                "reader shape {}x{} != {GROUP_ORDER}x{READER_WIDTH}",
                reader.rows, reader.cols
            ));
        }
        let v = parent.cfg.vocab;
        if wg.rows != v || wg.cols != READER_WIDTH {
            return Err(format!(
                "wg shape {}x{} != {v}x{READER_WIDTH}",
                wg.rows, wg.cols
            ));
        }
        if action_codes.len() != v {
            return Err("action code count != vocab".into());
        }
        if action_codes.iter().any(|&c| c as usize >= PALETTE_SIZE) {
            return Err("action code outside the palette".into());
        }
        for r in 0..GROUP_ORDER {
            if reader.shift(r) != READER_SHIFT {
                return Err(format!(
                    "reader row {r} shift {} != {READER_SHIFT}",
                    reader.shift(r)
                ));
            }
        }
        for r in 0..v {
            if wg.shift(r) != OUTPUT_SHIFT {
                return Err(format!(
                    "wg row {r} shift {} != {OUTPUT_SHIFT}",
                    wg.shift(r)
                ));
            }
        }
        let core = Self {
            parent,
            reader,
            wg,
            action_codes,
            palette,
            arm,
        };
        core.validate_envelope()?;
        Ok(core)
    }

    /// The parent's declared maximum absolute score, from its own envelope declaration.
    pub fn parent_declared_max_abs(&self) -> i64 {
        let bias = (BIAS_CODE_MAX as i64) << self.parent.cfg.bias_scale_bits;
        let h_max = if self.parent.cfg.norm_bits == 0 {
            PRIOR_CLAMP as i64
        } else {
            1i64 << self.parent.cfg.norm_bits
        };
        let acc = self.parent.cfg.dv as i64 * h_max;
        let mut w_max = 0i64;
        for r in 0..self.parent.cfg.vocab {
            let bound = acc
                .checked_shl(self.parent.w_o.shift(r))
                .unwrap_or(i64::MAX / 8);
            w_max = w_max.max(bound);
        }
        bias + w_max
    }

    /// Validate that parent bound plus the residual bound cannot approach `i32::MAX`.
    pub fn validate_envelope(&self) -> Result<(), String> {
        let total = self
            .parent_declared_max_abs()
            .saturating_add(RESIDUAL_MAX_ABS);
        if total > (i32::MAX as i64) / 2 {
            return Err(format!(
                "combined parent+residual envelope {total} exceeds half of i32::MAX; the integer \
                 forward could wrap"
            ));
        }
        Ok(())
    }

    /// Hard palette action for a token.
    #[inline]
    pub fn action(&self, token: u32) -> usize {
        let v = self.parent.cfg.vocab;
        self.action_codes[(token as usize).min(v - 1)] as usize
    }

    /// Number of older-prefix tokens for prediction position `i` of a window.
    #[inline]
    pub fn older_len(i: usize) -> usize {
        if i < 2 {
            0
        } else {
            (i - 1) - i.saturating_sub(63)
        }
    }

    /// Chronological product over the older prefix `[max(0,i-63), i-1)`, or `None` when empty.
    pub fn state_older(&self, tokens: &[u32], i: usize) -> Option<usize> {
        if i < 2 {
            return None;
        }
        let start = i.saturating_sub(63);
        let end = i - 1;
        if end <= start {
            return None;
        }
        let t = group_table();
        let mut q = t.identity as usize;
        for &tok in &tokens[start..end] {
            let k = self.action(tok);
            let gamma = self.palette.elements[k] as usize;
            q = t.product[q * ROW_STRIDE + gamma] as usize;
        }
        Some(q)
    }

    /// Local-tail state: the product of the two local tokens' palette actions, or `None` when the
    /// older prefix is empty (the same availability mask as the primary arm).
    pub fn state_tail(&self, tokens: &[u32], i: usize) -> Option<usize> {
        if i < 2 {
            return None;
        }
        let t = group_table();
        let mut q = t.identity as usize;
        for &tok in &tokens[i - 1..=i] {
            let k = self.action(tok);
            let gamma = self.palette.elements[k] as usize;
            q = t.product[q * ROW_STRIDE + gamma] as usize;
        }
        Some(q)
    }

    /// The residual read: `(sum_j Wcode[v,j] * Rcode[q,j]) << 8`.
    pub fn residual_scores(&self, q: usize) -> Vec<i32> {
        let mut h = vec![0i32; READER_WIDTH];
        for (j, slot) in h.iter_mut().enumerate() {
            *slot = self.reader.weight(q, j) << READER_SHIFT;
        }
        let mut out = self.wg.forward_i32(&h);
        // `forward_i32` already applied OUTPUT_SHIFT; assert the declared identity on one entry.
        debug_assert!(READER_SHIFT + OUTPUT_SHIFT == RESIDUAL_SHIFT);
        if false {
            out.clear();
        }
        out
    }

    /// Total integer scores: frozen parent plus the optional residual.
    pub fn int_logits(&self, prev: usize, cur: usize, q: Option<usize>) -> Vec<i32> {
        let mut z = self.parent.int_logits(prev, cur, true);
        if let Some(q) = q {
            let r = self.residual_scores(q);
            for (a, b) in z.iter_mut().zip(r.iter()) {
                *a += *b;
            }
        }
        z
    }

    /// **Arm-aware state selection** shared by training, evaluation and generation.
    ///
    /// The local-tail arm must never fall back to the older-prefix state during generation; its
    /// teacher-forced loss uses [`Self::state_tail`], so generation must too.
    pub fn state_for_arm(&self, tokens: &[u32], i: usize) -> Option<usize> {
        if self.arm == Arm::LearnedTail as u8 {
            self.state_tail(tokens, i)
        } else {
            self.state_older(tokens, i)
        }
    }

    /// Greedy continuation that recomputes the arm's state from the bounded context (no separate
    /// eviction subsystem).
    pub fn generate(&self, prompt: &[u32], n_new: usize) -> Vec<u32> {
        let mut toks = prompt.to_vec();
        let v = self.parent.cfg.vocab;
        for _ in 0..n_new {
            let i = toks.len() - 1;
            let prev = if i == 0 {
                self.parent.cfg.pad_row()
            } else {
                (toks[i - 1] as usize).min(v - 1)
            };
            let cur = (toks[i] as usize).min(v - 1);
            let q = self.state_for_arm(&toks, i);
            let z = self.int_logits(prev, cur, q);
            let mut best = 0usize;
            for r in 1..z.len() {
                if z[r] > z[best] {
                    best = r;
                }
            }
            toks.push(best as u32);
        }
        toks[prompt.len()..].to_vec()
    }

    pub fn weight_bytes(&self) -> usize {
        self.reader.weight_bytes() + self.wg.weight_bytes() + self.action_codes.len() / 2
    }
}

