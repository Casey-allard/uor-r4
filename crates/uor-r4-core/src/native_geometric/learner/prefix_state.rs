pub const PREFIX_MAGIC: &[u8; 4] = b"CPXS";
pub const PREFIX_FORMAT_VERSION: u32 = 1;

impl PrefixTrainer {
    pub fn checkpoint_bytes(&self) -> Vec<u8> {
        let mut o = Vec::new();
        o.extend_from_slice(PREFIX_MAGIC);
        o.extend_from_slice(&PREFIX_FORMAT_VERSION.to_le_bytes());
        o.extend_from_slice(&(self.parent.cfg.vocab as u32).to_le_bytes());
        o.extend_from_slice(&(self.window as u32).to_le_bytes());
        o.extend_from_slice(&(self.batch as u32).to_le_bytes());
        o.extend_from_slice(&(self.updates as u32).to_le_bytes());
        o.extend_from_slice(&(self.warmup_updates as u32).to_le_bytes());
        o.push(self.arm as u8);
        o.extend_from_slice(&self.seed.to_le_bytes());
        o.extend_from_slice(&self.palette.elements);
        o.push(self.palette.identity);
        o.extend_from_slice(&self.reader_updates.to_le_bytes());
        o.extend_from_slice(&self.action_updates.to_le_bytes());
        o.extend_from_slice(&self.pass.to_le_bytes());
        o.extend_from_slice(&self.parent_sha256);
        o.extend_from_slice(&self.data_identity);
        for block in [
            &self.r_master,
            &self.w_master,
            &self.a_logits,
            &self.r_m,
            &self.r_v,
            &self.w_m,
            &self.w_v,
            &self.a_m,
            &self.a_v,
        ] {
            o.extend_from_slice(&(block.len() as u64).to_le_bytes());
            for f in block.iter() {
                o.extend_from_slice(&f.to_le_bytes());
            }
        }
        o
    }

    /// Load a checkpoint, validating config/arm/group/base identity before mutating anything.
    pub fn resume_from(&mut self, bytes: &[u8]) -> Result<(), String> {
        let mut c = 0usize;
        let take = |c: &mut usize, n: usize| -> Result<&[u8], String> {
            let end = c.checked_add(n).ok_or("size overflow")?;
            if end > bytes.len() {
                return Err("truncated checkpoint".into());
            }
            let s = &bytes[*c..end];
            *c = end;
            Ok(s)
        };
        if take(&mut c, 4)? != PREFIX_MAGIC {
            return Err("bad prefix checkpoint magic".into());
        }
        let u32_at = |c: &mut usize| -> Result<u32, String> {
            Ok(u32::from_le_bytes(take(c, 4)?.try_into().unwrap()))
        };
        let u64_at = |c: &mut usize| -> Result<u64, String> {
            Ok(u64::from_le_bytes(take(c, 8)?.try_into().unwrap()))
        };
        if u32_at(&mut c)? != PREFIX_FORMAT_VERSION {
            return Err("unsupported prefix checkpoint version".into());
        }
        let vocab = u32_at(&mut c)? as usize;
        let window = u32_at(&mut c)? as usize;
        let batch = u32_at(&mut c)? as usize;
        let updates = u32_at(&mut c)? as usize;
        let warmup = u32_at(&mut c)? as usize;
        let arm = Arm::from_u8(take(&mut c, 1)?[0])?;
        let seed = u64_at(&mut c)?;
        let mut elements = [0u8; PALETTE_SIZE];
        elements.copy_from_slice(take(&mut c, PALETTE_SIZE)?);
        let identity = take(&mut c, 1)?[0];
        let reader_updates = u64_at(&mut c)?;
        let action_updates = u64_at(&mut c)?;
        let pass = u32_at(&mut c)?;
        let mut parent_sha = [0u8; 32];
        parent_sha.copy_from_slice(take(&mut c, 32)?);
        let mut data_identity = [0u8; 32];
        data_identity.copy_from_slice(take(&mut c, 32)?);

        if vocab != self.parent.cfg.vocab
            || window != self.window
            || batch != self.batch
            || updates != self.updates
            || warmup != self.warmup_updates
            || arm != self.arm
            || seed != self.seed
            || elements != self.palette.elements
            || identity != self.palette.identity
        {
            return Err("prefix checkpoint configuration/arm/seed/palette differs".into());
        }
        if parent_sha != self.parent_sha256 {
            return Err("prefix checkpoint parent artifact differs".into());
        }
        let wants = [
            self.r_master.len(),
            self.w_master.len(),
            self.a_logits.len(),
            self.r_m.len(),
            self.r_v.len(),
            self.w_m.len(),
            self.w_v.len(),
            self.a_m.len(),
            self.a_v.len(),
        ];
        let mut blocks: Vec<Vec<f32>> = Vec::new();
        for want in wants {
            let len = u64_at(&mut c)? as usize;
            if len != want {
                return Err("prefix checkpoint block length differs".into());
            }
            let mut v = Vec::with_capacity(len);
            for _ in 0..len {
                let x = f32::from_le_bytes(take(&mut c, 4)?.try_into().unwrap());
                if !x.is_finite() {
                    return Err("prefix checkpoint holds a non-finite value".into());
                }
                v.push(x);
            }
            blocks.push(v);
        }
        if c != bytes.len() {
            return Err(format!("{} trailing checkpoint bytes", bytes.len() - c));
        }
        if blocks[4].iter().any(|x| *x < 0.0)
            || blocks[6].iter().any(|x| *x < 0.0)
            || blocks[8].iter().any(|x| *x < 0.0)
        {
            return Err("prefix checkpoint second moments are invalid".into());
        }
        let mut it = blocks.into_iter();
        self.r_master = it.next().unwrap();
        self.w_master = it.next().unwrap();
        self.a_logits = it.next().unwrap();
        self.r_m = it.next().unwrap();
        self.r_v = it.next().unwrap();
        self.w_m = it.next().unwrap();
        self.w_v = it.next().unwrap();
        self.a_m = it.next().unwrap();
        self.a_v = it.next().unwrap();
        self.reader_updates = reader_updates;
        self.action_updates = action_updates;
        self.pass = pass;
        self.data_identity = data_identity;
        Ok(())
    }
}

