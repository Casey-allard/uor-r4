#[derive(Clone, Copy, PartialEq, Eq, Hash, Debug)]
pub enum Arm {
    /// Learned older-prefix actions and reader/output.
    LearnedOlder = 0,
    /// The initial hard action map is frozen; reader/output trained.
    FixedOlder = 1,
    /// Same sizes, but the state is the local pair product only.
    LearnedTail = 2,
}

impl Arm {
    pub fn name(self) -> &'static str {
        match self {
            Arm::LearnedOlder => "learned_older_prefix",
            Arm::FixedOlder => "fixed_action_older_prefix",
            Arm::LearnedTail => "learned_local_tail",
        }
    }
    pub fn from_u8(x: u8) -> Result<Self, String> {
        match x {
            0 => Ok(Arm::LearnedOlder),
            1 => Ok(Arm::FixedOlder),
            2 => Ok(Arm::LearnedTail),
            _ => Err("unknown arm".into()),
        }
    }
    /// Whether action logits are updated after warm-up.
    pub fn trains_actions(self) -> bool {
        matches!(self, Arm::LearnedOlder | Arm::LearnedTail)
    }
    /// Whether the state is built from the older prefix (as opposed to the local pair only).
    pub fn uses_older_prefix(self) -> bool {
        !matches!(self, Arm::LearnedTail)
    }
}

fn xorshift(st: &mut u64) -> u64 {
    *st ^= *st << 13;
    *st ^= *st >> 7;
    *st ^= *st << 17;
    *st
}

fn seed_state(seed: u64, tag: u64) -> u64 {
    // SplitMix-style tag mixing so per-token initial choices are independent of iteration order.
    let mut z = seed
        .wrapping_add(0x9E37_79B9_7F4A_7C15)
        .wrapping_add(tag.wrapping_mul(0xBF58_476D_1CE4_E5B9));
    z = (z ^ (z >> 30)).wrapping_mul(0xBF58_476D_1CE4_E5B9);
    z = (z ^ (z >> 27)).wrapping_mul(0x94D0_49BB_1331_11EB);
    z ^ (z >> 31)
}

/// Offline trainer for one arm. Never mutates the frozen parent.
#[derive(Clone, Debug)]
pub struct PrefixTrainer {
    pub parent: PriorCore,
    pub palette: Palette,
    pub arm: Arm,
    pub seed: u64,
    pub window: usize,
    pub batch: usize,
    pub updates: usize,
    pub warmup_updates: usize,
    pub r_master: Vec<f32>,
    pub w_master: Vec<f32>,
    pub a_logits: Vec<f32>,
    /// Frozen hard action map for the fixed-action arm.
    pub frozen_actions: Vec<u8>,
    r_m: Vec<f32>,
    r_v: Vec<f32>,
    w_m: Vec<f32>,
    w_v: Vec<f32>,
    a_m: Vec<f32>,
    a_v: Vec<f32>,
    pub reader_updates: u64,
    pub action_updates: u64,
    pub pass: u32,
    /// L2 norms of the last batch's mean gradients, for reporting only.
    pub last_grad_norm_reader: f64,
    pub last_grad_norm_action: f64,
    pub parent_sha256: [u8; 32],
    pub data_identity: [u8; 32],
}

impl PrefixTrainer {
    pub fn new(
        parent: PriorCore,
        palette: Palette,
        arm: Arm,
        seed: u64,
        window: usize,
        batch: usize,
        updates: usize,
        warmup_updates: usize,
        parent_sha256: [u8; 32],
    ) -> Result<Self, String> {
        let v = parent.cfg.vocab;
        if palette.closure_size() != GROUP_ORDER {
            return Err("palette closure is not the full group".into());
        }
        let mut st = seed ^ 0x5DEE_CE66_D1CE_B00D;
        // Reader masters: seeded +/- 1, so the reader is nonzero from the start and every output
        // row receives a gradient through the reader.
        let r_master: Vec<f32> = (0..GROUP_ORDER * READER_WIDTH)
            .map(|_| {
                if xorshift(&mut st) & 1 == 0 {
                    1.0
                } else {
                    -1.0
                }
            })
            .collect();
        // Output masters exactly zero: step 0 must reproduce the parent scores exactly.
        let w_master = vec![0.0f32; v * READER_WIDTH];
        // Action rows: one seeded palette choice at 0.1, the rest zero.
        let mut a_logits = vec![0.0f32; v * PALETTE_SIZE];
        let mut initial = vec![0u8; v];
        for (t, slot) in initial.iter_mut().enumerate() {
            let id = (seed_state(seed, t as u64) % PALETTE_SIZE as u64) as usize;
            *slot = id as u8;
            a_logits[t * PALETTE_SIZE + id] = 0.1;
        }
        let frozen_actions = match arm {
            Arm::FixedOlder => initial.clone(),
            _ => Vec::new(),
        };
        Ok(Self {
            parent,
            palette,
            arm,
            seed,
            window,
            batch,
            updates,
            warmup_updates,
            r_m: vec![0.0; r_master.len()],
            r_v: vec![0.0; r_master.len()],
            w_m: vec![0.0; w_master.len()],
            w_v: vec![0.0; w_master.len()],
            a_m: vec![0.0; a_logits.len()],
            a_v: vec![0.0; a_logits.len()],
            r_master,
            w_master,
            a_logits,
            frozen_actions,
            reader_updates: 0,
            action_updates: 0,
            pass: 0,
            last_grad_norm_reader: 0.0,
            last_grad_norm_action: 0.0,
            parent_sha256,
            data_identity: [0u8; 32],
        })
    }

    /// The actual initial hard action map.
    pub fn initial_actions(&self) -> Vec<u8> {
        (0..self.parent.cfg.vocab)
            .map(|t| argmax8(&self.a_logits[t * PALETTE_SIZE..(t + 1) * PALETTE_SIZE]) as u8)
            .collect()
    }

    /// The current hard action map.
    pub fn hard_actions(&self) -> Vec<u8> {
        match self.arm {
            Arm::FixedOlder => self.frozen_actions.clone(),
            _ => self.initial_actions(),
        }
    }

    /// Build the served hard core from the current masters.
    pub fn hard_core(&self) -> Result<PrefixCore, String> {
        let v = self.parent.cfg.vocab;
        let (rp, rs) = pack_fixed(&self.r_master, GROUP_ORDER, READER_WIDTH, READER_SHIFT);
        let (wp, ws) = pack_fixed(&self.w_master, v, READER_WIDTH, OUTPUT_SHIFT);
        let reader = TernaryLinear::from_packed(rp, rs, GROUP_ORDER, READER_WIDTH)?;
        let wg = TernaryLinear::from_packed(wp, ws, v, READER_WIDTH)?;
        PrefixCore::from_parts(
            self.parent.clone(),
            reader,
            wg,
            self.hard_actions(),
            self.palette.clone(),
            self.arm as u8,
        )
    }

    /// One hard-forward training batch. Returns the mean uncapped cross-entropy in bits over the
    /// actual scored targets. When `apply_actions` is false the action logits are untouched (reader
    /// warm-up).
    pub fn train_batch(
        &mut self,
        windows: &[Vec<u32>],
        cache: &mut ParentCache,
        apply_actions: bool,
    ) -> Result<f64, String> {
        let v = self.parent.cfg.vocab;
        let core = self.hard_core()?;
        let mut gw = vec![0.0f32; v * READER_WIDTH];
        let mut gr = vec![0.0f32; GROUP_ORDER * READER_WIDTH];
        let mut da = vec![0.0f32; v * PALETTE_SIZE];
        let mut loss = 0.0f64;
        let mut scored = 0usize;

        let scale = (-(core.parent.cfg.f_bits as f64)).exp2();
        let inv_ln2 = 1.0 / std::f64::consts::LN_2;

        for w in windows {
            for i in 0..w.len().saturating_sub(1) {
                let prev = if i == 0 {
                    core.parent.cfg.pad_row()
                } else {
                    (w[i - 1] as usize).min(v - 1)
                };
                let cur = (w[i] as usize).min(v - 1);
                let target = w[i + 1];
                let z_parent = cache.z_for(&core.parent, prev, cur).to_vec();
                let q = if core.arm == Arm::LearnedTail as u8 {
                    core.state_tail(w, i)
                } else {
                    core.state_older(w, i)
                };
                let z = if let Some(q) = q {
                    let r = core.residual_scores(q);
                    let mut z = z_parent.clone();
                    for (a, b) in z.iter_mut().zip(r.iter()) {
                        *a += *b;
                    }
                    z
                } else {
                    z_parent.clone()
                };
                // One softmax pass serves both the loss and the score gradient.
                let p = softmax_scaled(&z, scale);
                let t = (target as usize).min(v - 1);
                loss += -(p[t].max(1e-300).ln()) * inv_ln2;
                scored += 1;

                if q.is_none() {
                    continue;
                }
                let q = q.unwrap();

                // dLoss_nats/dZ with the declared 2^-F score-to-logit scale.
                let mut dz = vec![0.0f64; v];
                for (r, slot) in dz.iter_mut().enumerate() {
                    *slot = (p[r] - if r == t { 1.0 } else { 0.0 }) * scale * inv_ln2;
                }

                // g[j] = 256 * sum_v dZ[v] * Wcode[v,j]; gW[v,j] = 256 * dZ[v] * Rcode[q,j].
                let mut g = [0.0f32; READER_WIDTH];
                let rq: [i32; READER_WIDTH] = std::array::from_fn(|j| core.reader.weight(q, j));
                for r in 0..v {
                    let dzv = dz[r] as f32;
                    if dzv == 0.0 {
                        continue;
                    }
                    let scaled = 256.0 * dzv;
                    for j in 0..READER_WIDTH {
                        if rq[j] != 0 {
                            gw[r * READER_WIDTH + j] += scaled * rq[j] as f32;
                        }
                        let wc = core.wg.weight(r, j);
                        if wc != 0 {
                            g[j] += dzv * wc as f32;
                        }
                    }
                }
                for x in g.iter_mut() {
                    *x *= 256.0;
                }

                // Reader adjoint for the read row.
                for j in 0..READER_WIDTH {
                    gr[q * READER_WIDTH + j] += g[j];
                }

                // State adjoint u[s] = sum_j g[j] * Rcode[s,j].
                let mut u = vec![0.0f32; GROUP_ORDER];
                for (s, us) in u.iter_mut().enumerate() {
                    let mut acc = 0.0f32;
                    for j in 0..READER_WIDTH {
                        let rc = core.reader.weight(s, j);
                        if rc != 0 {
                            acc += g[j] * rc as f32;
                        }
                    }
                    *us = acc;
                }

                // Backpropagate through the bounded chain: explicit reset, no future-target leakage.
                let chain: Vec<usize> = if core.arm == Arm::LearnedTail as u8 {
                    vec![i - 1, i]
                } else {
                    (i.saturating_sub(63)..i - 1).collect()
                };
                let mut qs = Vec::with_capacity(chain.len() + 1);
                qs.push(group_table().identity as usize);
                for &j in &chain {
                    let k = core.action(w[j]);
                    let gamma = core.palette.elements[k] as usize;
                    let last = *qs.last().unwrap();
                    qs.push(group_table().product[last * ROW_STRIDE + gamma] as usize);
                }
                debug_assert_eq!(
                    *qs.last().unwrap(),
                    q,
                    "chain state must equal the read state"
                );
                let mut next_u = vec![0.0f32; GROUP_ORDER];
                for tstep in (0..chain.len()).rev() {
                    let j = chain[tstep];
                    let tok = w[j] as usize;
                    let k_t = core.action(w[j]);
                    let q_before = qs[tstep];
                    let gamma_t = core.palette.elements[k_t] as usize;
                    for (k, &gamma) in core.palette.elements.iter().enumerate() {
                        let h =
                            group_table().product[q_before * ROW_STRIDE + gamma as usize] as usize;
                        da[tok * PALETTE_SIZE + k] += u[h];
                    }
                    for s in 0..GROUP_ORDER {
                        next_u[s] = u[group_table().product[s * ROW_STRIDE + gamma_t] as usize];
                    }
                    std::mem::swap(&mut u, &mut next_u);
                }
            }
        }

        if scored == 0 {
            return Err("empty batch".into());
        }
        let inv = 1.0 / scored as f64;
        loss *= inv;

        // Mean gradients over the actual scored-target count.
        let inv32 = inv as f32;
        for x in gw.iter_mut() {
            *x *= inv32;
        }
        for x in gr.iter_mut() {
            *x *= inv32;
        }
        for x in da.iter_mut() {
            *x *= inv32;
        }
        self.last_grad_norm_reader = gr
            .iter()
            .chain(gw.iter())
            .map(|x| (*x as f64) * (*x as f64))
            .sum::<f64>()
            .sqrt();
        self.last_grad_norm_action = da
            .iter()
            .map(|x| (*x as f64) * (*x as f64))
            .sum::<f64>()
            .sqrt();

        // Softmax Jacobian on the offline action logits, applied once per batch (the logits are
        // constant inside the batch, so linear accumulation is equivalent).
        let mut d_a = vec![0.0f32; v * PALETTE_SIZE];
        for tok in 0..v {
            let row = &self.a_logits[tok * PALETTE_SIZE..(tok + 1) * PALETTE_SIZE];
            let pi = softmax8(row);
            let mut dot = 0.0f32;
            for k in 0..PALETTE_SIZE {
                dot += pi[k] * da[tok * PALETTE_SIZE + k];
            }
            for k in 0..PALETTE_SIZE {
                d_a[tok * PALETTE_SIZE + k] = pi[k] * (da[tok * PALETTE_SIZE + k] - dot);
            }
        }

        // Adam: reader/output age and action age advance independently.
        let next_reader_age = self.reader_updates + 1;
        adam_step(
            &mut self.r_master,
            &mut self.r_m,
            &mut self.r_v,
            &gr,
            READER_LR,
            next_reader_age,
        );
        adam_step(
            &mut self.w_master,
            &mut self.w_m,
            &mut self.w_v,
            &gw,
            READER_LR,
            next_reader_age,
        );
        self.reader_updates = next_reader_age;
        if apply_actions && self.arm.trains_actions() {
            let next_action_age = self.action_updates + 1;
            adam_step(
                &mut self.a_logits,
                &mut self.a_m,
                &mut self.a_v,
                &d_a,
                ACTION_LR,
                next_action_age,
            );
            self.action_updates = next_action_age;
        }
        Ok(loss)
    }

    pub fn state_bytes(&self) -> usize {
        (self.r_master.len() + self.w_master.len() + self.a_logits.len()) * 4
            + (self.r_m.len() + self.r_v.len() + self.w_m.len() + self.w_v.len()) * 4
            + (self.a_m.len() + self.a_v.len()) * 4
    }
}

fn argmax8(a: &[f32]) -> usize {
    let mut best = 0usize;
    for k in 1..PALETTE_SIZE {
        if a[k] > a[best] {
            best = k;
        }
    }
    best
}

fn softmax8(a: &[f32]) -> [f32; PALETTE_SIZE] {
    let mut max = a[0];
    for &x in &a[1..PALETTE_SIZE] {
        if x > max {
            max = x;
        }
    }
    let mut out = [0.0f32; PALETTE_SIZE];
    let mut sum = 0.0f32;
    for k in 0..PALETTE_SIZE {
        let e = (a[k] - max).exp();
        out[k] = e;
        sum += e;
    }
    for x in out.iter_mut() {
        *x /= sum;
    }
    out
}

fn softmax_scaled(z: &[i32], scale: f64) -> Vec<f64> {
    let mut max = f64::NEG_INFINITY;
    for &v in z {
        let s = v as f64 * scale;
        if s > max {
            max = s;
        }
    }
    let mut p = Vec::with_capacity(z.len());
    let mut sum = 0.0f64;
    for &v in z {
        let e = (v as f64 * scale - max).exp();
        p.push(e);
        sum += e;
    }
    for x in p.iter_mut() {
        *x /= sum;
    }
    p
}

/// One Adam step with bias correction at the update's own age, then a master clamp to `[-1, 1]`.
fn adam_step(master: &mut [f32], m: &mut [f32], vv: &mut [f32], grad: &[f32], lr: f32, age: u64) {
    assert_eq!(master.len(), grad.len());
    let b1 = BETA1;
    let b2 = BETA2;
    let bc1 = 1.0 - b1.powi(age.min(100_000) as i32);
    let bc2 = 1.0 - b2.powi(age.min(100_000) as i32);
    for i in 0..master.len() {
        let g = grad[i];
        m[i] = b1 * m[i] + (1.0 - b1) * g;
        vv[i] = b2 * vv[i] + (1.0 - b2) * g * g;
        let mhat = m[i] / bc1;
        let vhat = vv[i] / bc2;
        master[i] -= lr * mhat / (vhat.sqrt() + ADAM_EPS);
        master[i] = master[i].clamp(-1.0, 1.0);
    }
}

