/// A bounded cache of frozen-parent integer scores keyed by the exact `(prev, cur)` pair. Shared by
/// every arm and invariant under the state permutation, which does not move the local pair.
#[derive(Default)]
pub struct ParentCache {
    map: HashMap<u32, Box<[i32]>>,
    pub hits: u64,
    pub misses: u64,
}

impl ParentCache {
    fn key(prev: usize, cur: usize, vocab: usize) -> u32 {
        ((prev as u32) * (vocab as u32)) + cur as u32
    }

    /// Cached parent scores, computing and storing them on first use.
    pub fn z_for(&mut self, parent: &PriorCore, prev: usize, cur: usize) -> &[i32] {
        let k = Self::key(prev, cur, parent.cfg.vocab);
        if !self.map.contains_key(&k) {
            self.misses += 1;
            let z = parent.int_logits(prev, cur, true);
            self.map.insert(k, z.into_boxed_slice());
        } else {
            self.hits += 1;
        }
        &self.map[&k]
    }

    pub fn entries(&self) -> usize {
        self.map.len()
    }

    pub fn bytes(&self) -> usize {
        self.map
            .values()
            .map(|v| v.len() * std::mem::size_of::<i32>())
            .sum()
    }
}

