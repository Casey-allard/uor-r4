#[test]
fn test_adversarial_delayed_stop_token_suppression() {
    let bundle = Bundle::synthetic_for_test();
    // Seed 1300 generates token 4 ("<|user|>") on step 0, and then token 6 (<|turn_end|>) on step 1
    let seed = 1300;
    let mut session = ChatSession::new(&bundle, None, seed).expect("new session");
    session.set_policy(SamplePolicy::Categorical { top_k: 4096 });

    let initial_telemetry = session.telemetry();
    let stop_tokens = [RoleToken::TurnEnd.id(), RoleToken::EOS_ID];

    let mut stream = session
        .generate_stream("User turn 1", 50, &stop_tokens)
        .expect("generate stream");

    let mut emitted_chunks = Vec::new();
    for chunk in stream.by_ref() {
        emitted_chunks.push(chunk);
    }

    // 1. Text token was emitted
    assert_eq!(emitted_chunks, vec!["<|user|>".to_string()]);
    // 2. Stop token <|turn_end|> was suppressed
    let full_text = emitted_chunks.join("");
    assert!(!full_text.contains("<|turn_end|>"));

    assert!(stream.is_stopped());
    assert_eq!(
        stream.stop_reason(),
        Some(StreamStopReason::TurnEnd { token_id: 6 })
    );
    assert_eq!(stream.tokens_generated(), 1);
    assert_eq!(stream.generated_tokens(), &[4]);

    // 3. Dialogue memory contains prompt tokens, text token AND stop token
    let prompt_len = bundle
        .tokenizer()
        .encode("<|user|>User turn 1<|turn_end|><|assistant|>")
        .len() as u64;
    let post_telemetry = session.telemetry();
    assert_eq!(
        post_telemetry.dialogue_tokens_seen,
        initial_telemetry.dialogue_tokens_seen + prompt_len + 1 + 1 // prompt + 1 text + 1 stop
    );

    // 4. Ready for next turn
    assert!(session.ingest_user_turn("Next turn").is_ok());
    assert_eq!(session.telemetry().current_turn_id, 2);
}

#[test]
fn test_adversarial_immediate_stop_on_token_0() {
    let bundle = Bundle::synthetic_for_test();
    let mut session = ChatSession::new(&bundle, None, 42).expect("new session");
    session.set_policy(SamplePolicy::Greedy);

    // In greedy mode on synthetic model, token 4 (<|user|>) is predicted on token 0
    // We register token 4 as a custom stop token to test immediate stop on token 0
    let stop_tokens = [4u32, RoleToken::TurnEnd.id(), RoleToken::EOS_ID];

    let mut stream = session
        .generate_stream("Stop immediately", 100, &stop_tokens)
        .expect("generate stream");

    // The very first call to next() must immediately return None
    let first_chunk = stream.next();
    assert_eq!(
        first_chunk, None,
        "Stream must immediately terminate and return None on token 0 stop"
    );
    assert!(
        stream.is_stopped(),
        "Stream must be marked stopped on token 0"
    );
    assert_eq!(
        stream.tokens_generated(),
        0,
        "Tokens generated count must be strictly 0"
    );
    assert_eq!(
        stream.stop_reason(),
        Some(StreamStopReason::CustomStop { token_id: 4 }),
        "Stop reason must identify CustomStop with token 4"
    );

    // Subsequent calls to next() must also return None
    assert_eq!(stream.next(), None);
    assert_eq!(stream.next(), None);

    // Verify dialogue memory has token 4 appended
    let cursor = session.state().dialogue_cursor;
    let last_slot_idx = if cursor == 0 {
        session.state().dialogue_capacity - 1
    } else {
        cursor - 1
    };
    assert_eq!(
        session.state().dialogue_tokens[last_slot_idx],
        4,
        "Stop token 4 must be stepped into dialogue ring buffer"
    );

    // Verify session is ready for next turn
    let next_turn = session.ingest_user_turn("Followup prompt");
    assert!(next_turn.is_ok());
}

