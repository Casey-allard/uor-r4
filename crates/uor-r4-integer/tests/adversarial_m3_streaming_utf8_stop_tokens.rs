//! Adversarial Challenger Test Suite — Milestone M3:
//! Streaming UTF-8 Decoding, Stop-Token Suppression & Stream Lifecycle Invariants.
//! File: crates/uor-r4-integer/tests/adversarial_m3_streaming_utf8_stop_tokens.rs
//!
//! Empirical adversarial verification covering:
//! 1. IncrementalUtf8Decoder pathological byte splits:
//!    - 4-byte emojis (🦀, 🚀, 🧪, 🧠, 🤖, 🧬) split byte-by-byte (1 byte per call) across 4 calls:
//!      * 0 replacement characters (`\u{FFFD}`)
//!      * Exact character reconstruction
//!    - Arbitrary integer partitions of 4-byte, 3-byte, and 2-byte sequences:
//!      * 3-byte CJK characters (語, 漢, 字, 中, 文) across [1,1,1], [1,2], [2,1] splits
//!      * 2-byte accented letters (é, ü, ñ, ç, ö, α, β) across [1,1] splits
//!    - Invalid byte sequences followed by valid sequences:
//!      * Recovery without buffer corruption, hanging pending bytes, or crash
//!    - Trailing incomplete bytes flushed with `\u{FFFD}` cleanly upon termination
//!
//! 2. Stop-token suppression and lifecycle in ChatTokenStream:
//!    - `<|turn_end|>` (id 6) generated by model is NEVER yielded to consumer string stream
//!    - `<|eos|>` (id 1) generated by model is NEVER yielded to consumer string stream
//!    - Session state appends stop token internally to dialogue memory
//!    - Session enters ready state for next user turn with incremented turn counter
//!    - Immediate stop on token 0 (turn end / eos / custom stop as first generated token)
//!    - Delayed stop token after multiple text tokens: text tokens yielded, stop token suppressed

