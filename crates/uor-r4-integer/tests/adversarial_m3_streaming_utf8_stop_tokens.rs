#[test]
fn test_adversarial_utf8_mixed_stream_stress() {
    let text = "Hello, 世界! 🦀 Rust 🚀 is fun — 100% café & 🧪.";
    let bytes = text.as_bytes();

    // Adversarially split into pseudo-random chunks of varying sizes [1, 2, 3, 1, 4, 1, ...]
    let chunk_sizes = [1, 2, 3, 1, 4, 1, 2, 1, 3, 5, 2, 1, 1, 2, 4, 1, 3, 2];
    let mut decoder = IncrementalUtf8Decoder::new();
    let mut reconstructed = String::new();
    let mut offset = 0;
    let mut step = 0;

    while offset < bytes.len() {
        let size = chunk_sizes[step % chunk_sizes.len()].min(bytes.len() - offset);
        let slice = &bytes[offset..offset + size];
        offset += size;
        step += 1;

        if let Some(chunk) = decoder.push_bytes(slice) {
            assert!(
                !chunk.contains('\u{FFFD}'),
                "Emitted chunk '{chunk}' must not contain replacement characters during valid stream"
            );
            reconstructed.push_str(&chunk);
        }
    }

    if let Some(flushed) = decoder.flush() {
        reconstructed.push_str(&flushed);
    }

    assert_eq!(
        reconstructed, text,
        "Reconstructed text must match original source text 100% verbatim"
    );
    assert!(
        decoder.is_empty(),
        "Decoder buffer must be empty after stream completion"
    );
}

#[test]
fn test_adversarial_utf8_invalid_sequence_recovery() {
    let mut decoder = IncrementalUtf8Decoder::new();

    // 1. Standalone invalid byte 0xFF
    let out = decoder.push_bytes(&[0xFF]);
    assert_eq!(
        out.as_deref(),
        Some("\u{FFFD}"),
        "Invalid byte 0xFF must emit replacement character"
    );
    assert!(
        decoder.is_empty(),
        "Pending buffer must be cleared after consuming invalid byte"
    );

    // Feed valid sequence immediately following 0xFF
    let out = decoder.push_bytes(b"hello ");
    assert_eq!(
        out.as_deref(),
        Some("hello "),
        "Decoder must cleanly recover and emit valid ASCII"
    );
    assert!(decoder.is_empty());

    // 2. Orphaned continuation byte 0x80
    let out = decoder.push_bytes(&[0x80]);
    assert_eq!(
        out.as_deref(),
        Some("\u{FFFD}"),
        "Lone continuation byte 0x80 must emit replacement character"
    );
    assert!(decoder.is_empty());

    // Feed valid 4-byte emoji byte-by-byte
    let crab = "🦀".as_bytes();
    assert_eq!(decoder.push_bytes(&crab[0..1]), None);
    assert_eq!(decoder.push_bytes(&crab[1..2]), None);
    assert_eq!(decoder.push_bytes(&crab[2..3]), None);
    assert_eq!(decoder.push_bytes(&crab[3..4]), Some("🦀".to_string()));
    assert!(decoder.is_empty());

    // 3. Incomplete sequence truncated by non-continuation byte
    // 0xF0 0x9F (start of 4-byte emoji) followed by ASCII '!' (0x21)
    assert_eq!(decoder.push_bytes(&[0xF0, 0x9F]), None);
    assert_eq!(decoder.pending_len(), 2);

    let out = decoder.push_bytes(b"!");
    // The invalid 2-byte prefix is drained as replacement char
    assert_eq!(
        out.as_deref(),
        Some("\u{FFFD}"),
        "Truncated 4-byte prefix followed by ASCII must emit replacement char"
    );

    // Flush or next push drains the remaining valid byte
    let flushed = decoder.flush();
    assert_eq!(
        flushed.as_deref(),
        Some("!"),
        "Remaining valid ASCII byte must be cleanly flushed"
    );
    assert!(decoder.is_empty());
}

#[test]
fn test_adversarial_utf8_trailing_bytes_flush() {
    // Test 1: Incomplete 2-byte accent
    let mut decoder = IncrementalUtf8Decoder::new();
    assert_eq!(decoder.push_bytes(&[0xC3]), None);
    assert_eq!(decoder.pending_len(), 1);
    assert_eq!(decoder.flush(), Some("\u{FFFD}".to_string()));
    assert!(decoder.is_empty());
    assert_eq!(decoder.flush(), None);

    // Test 2: Incomplete 3-byte CJK
    assert_eq!(decoder.push_bytes(&[0xE8, 0xAA]), None);
    assert_eq!(decoder.pending_len(), 2);
    assert_eq!(decoder.flush(), Some("\u{FFFD}".to_string()));
    assert!(decoder.is_empty());

    // Test 3: Incomplete 4-byte emoji
    assert_eq!(decoder.push_bytes(&[0xF0, 0x9F, 0xA6]), None);
    assert_eq!(decoder.pending_len(), 3);
    assert_eq!(decoder.flush(), Some("\u{FFFD}".to_string()));
    assert!(decoder.is_empty());

    // Clean resumption after flush
    assert_eq!(decoder.push_bytes(b"Clean"), Some("Clean".to_string()));
    assert!(decoder.is_empty());
}

