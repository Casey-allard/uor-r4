fn find_immediate_stop_seed(bundle: &Bundle, prompt: &str, target: u32) -> Option<(u64, usize)> {
    let formatted = format!(
        "{}{}{}{}",
        RoleToken::USER_STR,
        prompt,
        RoleToken::TURN_END_STR,
        RoleToken::ASSISTANT_STR
    );
    let tokens = bundle.tokenizer().encode(&formatted);
    let prompt_len = tokens.len();
    let mut state = bundle.model().new_conversational_session();
    state.seal_persistent();
    let mut last_step = None;
    for &t in &tokens {
        last_step = Some(
            bundle
                .model()
                .step_conversational(
                    &mut state,
                    t,
                    uor_r4_integer::SlotTarget::Dialogue,
                    uor_r4_integer::ReadMode::Enabled,
                )
                .ok()?,
        );
    }
    let probs = &last_step?.probabilities;
    let policy = SamplePolicy::Categorical { top_k: 4096 };
    for seed in 1..200_000u64 {
        let mut sampler = uor_r4_integer::Sampler::new(seed);
        if let Ok(idx) = sampler.select(probs, policy) {
            if idx as u32 == target {
                return Some((seed, prompt_len));
            }
        }
    }
    None
}

#[test]
fn test_adversarial_stop_token_turn_end_suppression_and_state() {
    let bundle = Bundle::synthetic_for_test();
    let prompt = "User turn 1";
    let (seed, prompt_len) = find_immediate_stop_seed(&bundle, prompt, RoleToken::TurnEnd.id())
        .expect("must find a seed that produces TurnEnd on step 0");

    let mut session = ChatSession::new(&bundle, None, seed).expect("new session");
    session.set_policy(SamplePolicy::Categorical { top_k: 4096 });

    let initial_telemetry = session.telemetry();
    assert_eq!(initial_telemetry.current_turn_id, 0);

    let stop_tokens = [RoleToken::TurnEnd.id(), RoleToken::EOS_ID];

    // Ingest prompt and generate stream
    let mut stream = session
        .generate_stream(prompt, 50, &stop_tokens)
        .expect("generate stream");

    // Pull all items from stream
    let mut emitted_chunks = Vec::new();
    for chunk in stream.by_ref() {
        emitted_chunks.push(chunk);
    }

    // 1. VERIFY: Token 6 (<|turn_end|>) is NEVER yielded to consumer string stream
    let full_emitted_text = emitted_chunks.join("");
    assert!(
        !full_emitted_text.contains("<|turn_end|>"),
        "Consumer string stream must NEVER yield stop token <|turn_end|>"
    );
    assert!(
        !full_emitted_text.contains("<|eos|>"),
        "Consumer string stream must NEVER yield stop token <|eos|>"
    );

    // 2. VERIFY: Stream stop metadata
    assert!(
        stream.is_stopped(),
        "Stream must be marked stopped upon encountering <|turn_end|>"
    );
    assert_eq!(
        stream.stop_reason(),
        Some(StreamStopReason::TurnEnd { token_id: 6 }),
        "Stop reason must identify TurnEnd with token_id 6"
    );
    assert_eq!(
        stream.tokens_generated(),
        0,
        "Stop token on token 0 must not count as generated user token"
    );
    assert!(
        stream.generated_tokens().is_empty(),
        "Generated tokens slice must be empty when stopped on token 0"
    );

    // 3. VERIFY: Session state internally appended stop token 6 into dialogue memory
    let post_telemetry = session.telemetry();
    assert_eq!(
        post_telemetry.dialogue_tokens_seen,
        initial_telemetry.dialogue_tokens_seen + (prompt_len as u64) + 1,
        "Dialogue tokens seen must include the prompt tokens plus the stop token"
    );

    // Verify last slot token in dialogue ring buffer is token 6
    let cursor = session.state().dialogue_cursor;
    let last_slot_idx = if cursor == 0 {
        session.state().dialogue_capacity - 1
    } else {
        cursor - 1
    };
    assert_eq!(
        session.state().dialogue_tokens[last_slot_idx],
        RoleToken::TURN_END_ID,
        "Session dialogue memory ring buffer must record stop token 6 at current cursor"
    );

    // 4. VERIFY: Session is ready for the next user turn
    let turn2_result = session.ingest_user_turn("User turn 2");
    assert!(
        turn2_result.is_ok(),
        "Session must cleanly accept the next user turn"
    );
    assert_eq!(
        session.telemetry().current_turn_id,
        2,
        "Current turn ID must advance to turn 2"
    );
}

