#[test]
fn test_adversarial_utf8_emoji_byte_by_byte_split_4calls() {
    let emojis = [
        ("🦀", "Crab", "0xF0, 0x9F, 0xA6, 0x80"),
        ("🚀", "Rocket", "0xF0, 0x9F, 0x9A, 0x80"),
        ("🧪", "TestTube", "0xF0, 0x9F, 0xA7, 0xAA"),
        ("🧠", "Brain", "0xF0, 0x9F, 0xA7, 0xA0"),
        ("🤖", "Robot", "0xF0, 0x9F, 0xA4, 0x96"),
        ("🧬", "DNA", "0xF0, 0x9F, 0xA7, 0xAC"),
    ];

    for &(emoji, name, byte_desc) in &emojis {
        let bytes = emoji.as_bytes();
        assert_eq!(bytes.len(), 4, "Emoji {name} must be 4 bytes");

        let mut decoder = IncrementalUtf8Decoder::new();

        // Call 1: push byte 0
        let chunk0 = decoder.push_bytes(&bytes[0..1]);
        assert_eq!(
            chunk0, None,
            "Call 1 for {name} ({byte_desc}) must return None"
        );
        assert_eq!(decoder.pending_len(), 1);
        assert!(!decoder.is_empty());

        // Call 2: push byte 1
        let chunk1 = decoder.push_bytes(&bytes[1..2]);
        assert_eq!(
            chunk1, None,
            "Call 2 for {name} ({byte_desc}) must return None"
        );
        assert_eq!(decoder.pending_len(), 2);

        // Call 3: push byte 2
        let chunk2 = decoder.push_bytes(&bytes[2..3]);
        assert_eq!(
            chunk2, None,
            "Call 3 for {name} ({byte_desc}) must return None"
        );
        assert_eq!(decoder.pending_len(), 3);

        // Call 4: push byte 3 (completion)
        let chunk3 = decoder.push_bytes(&bytes[3..4]);
        assert_eq!(
            chunk3.as_deref(),
            Some(emoji),
            "Call 4 for {name} must return exactly {emoji}"
        );
        assert_eq!(
            decoder.pending_len(),
            0,
            "Pending buffer must be 0 after full 4-byte completion"
        );
        assert!(decoder.is_empty());

        // Verify zero replacement characters emitted throughout
        assert_ne!(
            chunk3.as_deref(),
            Some("\u{FFFD}"),
            "Emoji {name} must never produce replacement character \u{FFFD}"
        );
    }
}

#[test]
fn test_adversarial_utf8_emoji_arbitrary_partitions() {
    let emojis = ["🦀", "🚀", "🧪", "🧠"];
    // All 8 possible non-empty ordered integer compositions of 4:
    let compositions: &[&[usize]] = &[
        &[1, 1, 1, 1],
        &[1, 1, 2],
        &[1, 2, 1],
        &[2, 1, 1],
        &[2, 2],
        &[1, 3],
        &[3, 1],
        &[4],
    ];

    for &emoji in &emojis {
        let bytes = emoji.as_bytes();
        for &comp in compositions {
            let mut decoder = IncrementalUtf8Decoder::new();
            let mut assembled = String::new();
            let mut offset = 0;

            for (i, &size) in comp.iter().enumerate() {
                let slice = &bytes[offset..offset + size];
                offset += size;

                if let Some(chunk) = decoder.push_bytes(slice) {
                    assert!(
                        !chunk.contains('\u{FFFD}'),
                        "Emitted chunk must not contain replacement char \u{FFFD} for partition {comp:?}"
                    );
                    assembled.push_str(&chunk);
                }

                if i < comp.len() - 1 {
                    assert!(
                        assembled.is_empty(),
                        "Intermediate chunk in partition {comp:?} must not emit completed char early"
                    );
                }
            }

            assert_eq!(
                assembled, emoji,
                "Assembled output for partition {comp:?} must match {emoji}"
            );
            assert!(
                decoder.is_empty(),
                "Decoder buffer must be empty after full composition"
            );
        }
    }
}

#[test]
fn test_adversarial_utf8_cjk_3byte_splits() {
    let cjk_chars = [
        ("語", "Japanese/Chinese word", [0xE8u8, 0xAA, 0x9E]),
        ("漢", "Han character", [0xE6, 0xBC, 0xA2]),
        ("字", "Glyph character", [0xE5, 0xAD, 0x97]),
        ("中", "Middle/Center", [0xE4, 0xB8, 0xAD]),
        ("文", "Script/Culture", [0xE6, 0x96, 0x87]),
    ];

    for &(cjk_str, desc, expected_bytes) in &cjk_chars {
        assert_eq!(cjk_str.as_bytes(), &expected_bytes);

        // Composition 1: [1, 1, 1] byte-by-byte
        {
            let mut decoder = IncrementalUtf8Decoder::new();
            assert_eq!(
                decoder.push_bytes(&expected_bytes[0..1]),
                None,
                "{desc} byte 1 must return None"
            );
            assert_eq!(decoder.pending_len(), 1);

            assert_eq!(
                decoder.push_bytes(&expected_bytes[1..2]),
                None,
                "{desc} byte 2 must return None"
            );
            assert_eq!(decoder.pending_len(), 2);

            let res = decoder.push_bytes(&expected_bytes[2..3]);
            assert_eq!(
                res.as_deref(),
                Some(cjk_str),
                "{desc} byte 3 must complete {cjk_str}"
            );
            assert!(decoder.is_empty());
        }

        // Composition 2: [1, 2]
        {
            let mut decoder = IncrementalUtf8Decoder::new();
            assert_eq!(decoder.push_bytes(&expected_bytes[0..1]), None);
            assert_eq!(
                decoder.push_bytes(&expected_bytes[1..3]).as_deref(),
                Some(cjk_str)
            );
            assert!(decoder.is_empty());
        }

        // Composition 3: [2, 1]
        {
            let mut decoder = IncrementalUtf8Decoder::new();
            assert_eq!(decoder.push_bytes(&expected_bytes[0..2]), None);
            assert_eq!(
                decoder.push_bytes(&expected_bytes[2..3]).as_deref(),
                Some(cjk_str)
            );
            assert!(decoder.is_empty());
        }
    }
}

