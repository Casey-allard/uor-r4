/// One ahead-of-time PTX module: its file, the sources `build.rs` joins and compiles for it,
/// and the `extern "C" __global__` entry points it found in them, in declaration order.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct KernelModule {
    pub ptx: &'static str,
    pub sources: &'static [&'static str],
    pub kernels: &'static [&'static str],
}

/// Every PTX module's kernel list, generated by `build.rs` on every build (CPU builds included)
/// from the sources that module compiles. The dispatch refuses a name its module does not list
/// ([`cuda_stack_kernels::admit_launch`]).
pub mod kernel_lists {
    use super::KernelModule;
    include!(concat!(env!("OUT_DIR"), "/kernel_lists.rs"));
}

